################################################
#
# reduce -- reduces multi-CCD imaging photometry
#
################################################
def reduce(args=None):
    """``reduce [source] rfile (run first last [twait tmax]| flist) trim
    ([ncol nrow]) log lcplot implot [imwidth imheight imxpos imypos]
    psfplot [psfwidth psfheight psfxpos psfypos] [memory tupdate plotall]
    (ccd nx [cmap] msub xlo xhi ylo yhi iset (ilo ihi | plo phi))``

    Reduces a sequence of multi-CCD images, plotting lightcurves as
    images come in. It can extract with either simple aperture
    photometry or Tim Naylor's optimal photometry, on specific targets
    defined in an aperture file using |setaper|.

    reduce can source data from both the ULTRACAM and HiPERCAM
    servers, from local 'raw' ULTRACAM and HiPERCAM files (i.e. .xml +
    .dat for ULTRACAM, 3D FITS files for HiPERCAM) and from lists of
    HiPERCAM '.hcm' files. If you have data from a different
    instrument you should convert into the FITS-based hcm format.

    reduce is primarily configured from a file with extension
    ".red". This contains a series of directives, e.g. to say how to
    re-position and re-size the apertures. An initial reduce file is
    best generated with the script |genred| after you have created an
    aperture file. This contains lots of help on what to do. |genred|
    tries to get something usable fast for observing purposes, but the
    parameters can nearly always be tweaked to produce better
    outcomes.

    A reduce run can be terminated at any point with ctrl-C without doing
    any harm. You may often want to do this at the start in order to adjust
    parameters of the reduce file.

    Parameters:

        source : str [hidden]
           Data source, five options for built-in sources:

             |  'hs': HiPERCAM server
             |  'hl': local HiPERCAM FITS file
             |  'us': ULTRACAM server
             |  'ul': local ULTRACAM .xml/.dat files
             |  'hf': list of HiPERCAM hcm FITS-format files

           'hf' is used to look at sets of frames generated by 'grab'
           or converted from foreign data formats. The standard
           start-off default for ``source`` can be set using the
           environment variable HIPERCAM_DEFAULT_SOURCE. e.g. in bash
           :code:`export HIPERCAM_DEFAULT_SOURCE="us"` would ensure it
           always started with the ULTRACAM server by default.  If
           unspecified, it defaults to 'hl'.

           Any instruments installed via plugins can be used as a source by
           specifying either ``<instrument>:local`` or ``<instrument>:server``.

        run : str [if source ends 's' or 'l']
           run number to access, e.g. 'run034' or a file list. If a run,
           then reduce and log below will be set to have the same name by
           default.

        first : int [if source ends 's' or 'l']
           first frame to reduce. 1 = first frame; set = 0 to always try to
           get the most recent frame (if it has changed).

        last : int [if source ends 's' or 'l', hidden]
           last frame to reduce. 0 to just continue until the end.  This is
           not prompted for by default and must be set explicitly.  It
           defaults to 0 if not set. Its purpose is to allow accurate
           profiling tests.

        twait : float [if source ends 's'; hidden]
           time to wait between attempts to find a new exposure, seconds.

        tmax : float [if source ends 's'; hidden]
           maximum time to wait between attempts to find a new exposure,
           seconds.

        flist : string [if source ends 'f']
           name of file list

        trim : bool
           True to trim columns and/or rows off the edges of windows nearest
           the readout. Particularly useful with ULTRACAM windowed data where
           the first few rows and columns can contain bad data.

        ncol : int [if trim, hidden]
           Number of columns to remove (on left of left-hand window, and right
           of right-hand windows)

        nrow : int [if trim, hidden]
           Number of rows to remove (bottom of windows)

        rfile : str
           the "reduce" file, i.e. ASCII text file suitable for reading by
           ConfigParser. Best seen by example as it has many parts. If you
           are reducing a run, this will be set to have the same root name by
           default (but a different extension to avoid name clashes).

        log : str
           log file for the results. If you are reducing a run, this
           will be set to have the same root name by default (but a
           different extension to avoid name clashes)

        tkeep : float
           maximum number of minutes of data to store in internal buffers, 0
           for the lot. When large numbers of frames are stored, performance
           can be slowed (although I am not entirely clear why) in which case
           it makes sense to lose the earlier points (without affecting the
           saving to disk). This parameter also gives operation similar to that
           of "max_xrange" parameter in the ULTRACAM pipeline whereby just
           the last few minutes are shown.

        lcplot : bool
           flag to indicate you want to plot the light curve. Saves time not
           to especially in high-speed runs.

        implot : bool
           flag to indicate you want to plot images.

        imwidth : float [hidden]
            image display plot width in inches
            (0 for default, and note that this will also set the height to its default)

        imheight : float [hidden]
            image display plot height in inches
            (0 for default, and note that this will also set the height to its default)

        imxpos : int [hidden]
            image display plot X position in pixels

        imypos : int [hidden]
            image display plot Y position in pixels

        psfplot : bool
           flag to indicate you want to plot images after subtraction of PSF model.
           only valid if 'use_psf' is set to 'yes' in the reduce file.

        psfwidth : float [hidden]
            psf display plot width in inches
            (0 for default, and note that this will also set the height to its default)

        psfheight : float [hidden]
            psf display plot height in inches
            (0 for default, and note that this will also set the height to its default)

        psfxpos : int [hidden]
            psf display plot X position in pixels

        psfypos : int [hidden]
            psf display plot Y position in pixels

        memory : bool [hidden]
            stores the plot display dimensions (width, height) and position
            (xpos, ypos) at the end as defaults for next time.
            This helps if you are repeatedly re-starting the script.

        tupdate : float [hidden]
           target number of seconds between plot updates. This is to
           make the plots more responsive and get round issues with
           plots freezing until the next frame comes through which can
           be especially annoying with virtual desktops. Experiments
           with ULTRACAM@NTT indicated 0.2 to 0.6 secs or so works OK.
           Main impact seems to be on drpc CPU.

        plotall : bool [hidden]
           plot all images frames regardless of status (i.e. including blank frames
           when nskips are enabled). Defaults to False.
           The reduction will still be disabled for bad frames.

        ccd : string [if implot or psfplot]
           CCD(s) to plot, '0' for all, '1 3' to plot '1' and '3' only, etc.

        nx : int [if implot or psfplot]
           number of panels across to display.

        cmap : str [hidden]
           The matplotlib colour map to use. "Greys" gives the usual greyscale.
           "none" will give whatever the current default is. Many other choices:
           "viridis", "jet", "hot", "Oranges", etc. Enter an invalid one and
           the program will fail but return a huge list of possibles in the
           process. Note that some will not work well with the colours used
           to plot annotations.

        msub : bool [if implot or psfplot]
           subtract the median from each window before scaling for the
           image display or not. This happens after any bias subtraction.

        xlo : float [if implot or psfplot]
           left-hand X-limit for plot

        xhi : float [if implot or psfplot]
           right-hand X-limit for plot (can actually be < xlo)

        ylo : float [if implot or psfplot]
           lower Y-limit for plot

        yhi : float [if implot or psfplot]
           upper Y-limit for plot (can be < ylo)

        iset : string [if implot or psfplot]
           determines how the intensities are determined. There are three
           options: 'a' for automatic simply scales from the minimum to the
           maximum value found on a per CCD basis. 'd' for direct just takes
           two numbers from the user. 'p' for percentile dtermines levels
           based upon percentiles determined from the entire CCD on a per CCD
           basis.

        ilo : float [if implot or psfplot and iset='d']
           lower intensity level

        ihi : float [if implot or psfplot and iset='d']
           upper intensity level

        plo : float [if implot or psfplot and iset='p']
           lower percentile level

        phi : float [if implot or psfplot and iset='p']
           upper percentile level

    .. Warning::

       The transmission plot generated with reduce is not reliable in the
       case of optimal photometry since it is highly correlated with the
       seeing. If you are worried about the transmission during observing,
       you should always use normal aperture photometry.

    """

    command, args = cline.script_args(args)

    with Cline("HIPERCAM_ENV", ".hipercam", command, args) as cl:
        # register parameters
        cl.register("source", Cline.GLOBAL, Cline.HIDE)
        cl.register("run", Cline.GLOBAL, Cline.PROMPT)
        cl.register("first", Cline.LOCAL, Cline.PROMPT)
        cl.register("last", Cline.LOCAL, Cline.HIDE)
        cl.register("twait", Cline.LOCAL, Cline.HIDE)
        cl.register("tmax", Cline.LOCAL, Cline.HIDE)
        cl.register("flist", Cline.LOCAL, Cline.PROMPT)
        cl.register("trim", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ncol", Cline.GLOBAL, Cline.HIDE)
        cl.register("nrow", Cline.GLOBAL, Cline.HIDE)
        cl.register("rfile", Cline.GLOBAL, Cline.PROMPT)
        cl.register("log", Cline.GLOBAL, Cline.PROMPT)
        cl.register("tkeep", Cline.GLOBAL, Cline.PROMPT)
        cl.register("lcplot", Cline.LOCAL, Cline.PROMPT)
        cl.register("implot", Cline.LOCAL, Cline.PROMPT)
        cl.register("imwidth", Cline.LOCAL, Cline.HIDE)
        cl.register("imheight", Cline.LOCAL, Cline.HIDE)
        cl.register("imxpos", Cline.LOCAL, Cline.HIDE)
        cl.register("imypos", Cline.LOCAL, Cline.HIDE)
        cl.register("psfplot", Cline.LOCAL, Cline.PROMPT)
        cl.register("psfwidth", Cline.LOCAL, Cline.HIDE)
        cl.register("psfheight", Cline.LOCAL, Cline.HIDE)
        cl.register("psfxpos", Cline.LOCAL, Cline.HIDE)
        cl.register("psfypos", Cline.LOCAL, Cline.HIDE)
        cl.register("memory", Cline.LOCAL, Cline.HIDE)
        cl.register("tupdate", Cline.LOCAL, Cline.HIDE)
        cl.register("plotall", Cline.LOCAL, Cline.HIDE)
        cl.register("ccd", Cline.LOCAL, Cline.PROMPT)
        cl.register("nx", Cline.LOCAL, Cline.PROMPT)
        cl.register("cmap", Cline.LOCAL, Cline.HIDE)
        cl.register("msub", Cline.GLOBAL, Cline.PROMPT)
        cl.register("iset", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ilo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ihi", Cline.GLOBAL, Cline.PROMPT)
        cl.register("plo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("phi", Cline.LOCAL, Cline.PROMPT)
        cl.register("xlo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("xhi", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ylo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("yhi", Cline.GLOBAL, Cline.PROMPT)

        # get inputs
        default_source = os.environ.get("HIPERCAM_DEFAULT_SOURCE", "hl")
        source = cl.get_value(
            "source",
            "data source [hs, hl, us, ul, hf, or <instrument>:local/<instrument>:server]",
            default_source,
            lvals=available_instruments(),
        )

        # set some flags
        server_or_local = source.endswith("s") or source.endswith("l")

        if server_or_local:
            resource = cl.get_value("run", "run name", "run005")
            if source == "hs":
                # HiPERCAM doesn't like first=0, so allow -ve values
                first = cl.get_value("first", "first frame to plot", 1)
            else:
                first = cl.get_value("first", "first frame to plot", 1, 0)

            cl.set_default("last", 0)
            last = cl.get_value("last", "last frame to reduce", 0, 0)
            if last and last < first:
                print("Cannot set last < first unless last == 0")
                print("*** reduce aborted")
                exit(1)

            twait = cl.get_value(
                "twait", "time to wait for a new frame [secs]", 1.0, 0.0
            )
            tmax = cl.get_value(
                "tmax", "maximum time to wait for a new frame [secs]", 10.0, 0.0
            )

            # keep the reduce name and log in sync to save errors
            root = os.path.basename(resource)
            cl.set_default("rfile", cline.Fname(root, hcam.RED))
            cl.set_default("log", cline.Fname(root, hcam.LOG, cline.Fname.NEW))

        else:
            resource = cl.get_value(
                "flist", "file list", cline.Fname("files.lis", hcam.LIST)
            )
            first = 1
            last = 0

        trim = cl.get_value("trim", "do you want to trim edges of windows?", True)
        if trim:
            ncol = cl.get_value("ncol", "number of columns to trim from windows", 0)
            nrow = cl.get_value("nrow", "number of rows to trim from windows", 0)

        # the reduce file
        rfilen = cl.get_value(
            "rfile", "reduce file", cline.Fname("reduce.red", hcam.RED)
        )
        try:
            rfile = Rfile.read(rfilen)
        except hcam.HipercamError as err:
            # abort on failure to read as there are many ways to get reduce
            # files wrong
            print(err, file=sys.stderr)
            print("*** reduce aborted")
            exit(1)

        log = cl.get_value(
            "log",
            "name of log file to store results",
            cline.Fname("reduce.log", hcam.LOG, cline.Fname.NEW),
        )

        tkeep = cl.get_value(
            "tkeep",
            "number of minute of data to keep in internal buffers (0 for all)",
            0.0,
            0.0,
        )

        lcplot = cl.get_value("lcplot", "do you want to plot light curves?", True)

        implot = cl.get_value("implot", "do you want to plot images?", True)

        imwidth = cl.get_value(
            "imwidth", "image plot width [inches, 0 for default]", 0.0, 0.0
        )

        imheight = cl.get_value(
            "imheight", "image plot height [inches, 0 for default]", 0.0, 0.0
        )

        # iwidth and iheight are also options in the reduce file.
        # for backwards-compatibility, use them if given
        # TODO: is this right? Once we read them once they're saved in the Cline file
        # TODO: just remove them from the reduce file, along with all the PGPLOT bits
        if (
            rfile["general"]["iwidth"] > 0
            and rfile["general"]["iheight"] > 0
        ):
            if (
                imwidth != 0
                and imheight != 0
                and imwidth != rfile["general"]["iwidth"]
                and imheight != rfile["general"]["iheight"]
            ):
                # TODO: this will print every time, unless we overwrite the Cline file
                print("Using iwidth and iheight from reduce file")
            imwidth = rfile["general"]["iwidth"]
            imheight = rfile["general"]["iheight"]

        imxpos = cl.get_value(
            "imxpos", "image plot X position [screen pixels]", 0,
        )

        imypos = cl.get_value(
            "imypos", "image plot Y position [screen pixels]", 0,
        )

        use_psf = rfile["psf_photom"].get("use_psf", "no").lower().strip() != "no"
        if use_psf:
            if not HAS_PSF_OPTION:
                raise ValueError(
                    "'use_psf' is set to 'yes', but photutils not installed"
                )

            psfplot = cl.get_value(
                "psfplot", "do you want to plot residual of PSF model?", True
            )

            psfwidth = cl.get_value(
                "psfwidth", "PSF plot width [inches, 0 for default]", 0.0, 0.0
            )

            psfheight = cl.get_value(
                "psfheight", "PSF plot height [inches, 0 for default]", 0.0, 0.0
            )

            # like imwidth and imheight, use iwidth and iheight from the reduce file
            # if given for backwards-compatibility
            if rfile["general"]["iwidth"] > 0 and rfile["general"]["iheight"] > 0:
                if (
                    psfwidth != 0
                    and psfheight != 0
                    and psfwidth != rfile["general"]["iwidth"]
                    and psfheight != rfile["general"]["iheight"]
                ):
                    print("Using iwidth and iheight from reduce file")
                psfwidth = rfile["general"]["iwidth"]
                psfheight = rfile["general"]["iheight"]

            psfxpos = cl.get_value(
                "psfxpos", "PSF plot X position [screen pixels]", 0,
            )

            psfypos = cl.get_value(
                "psfypos", "PSF plot Y position [screen pixels]", 0,
            )

        else:
            psfplot = False

        memory = cl.get_value(
            "memory", "remember final plot geometry for next time?", True
        )

        tupdate = cl.get_value(
            "tupdate", "target time between plot updates [secs]", 0.2, 0.01
        )

        cl.set_default("plotall", False)
        plotall = cl.get_value(
            "plotall", "plot all frames, regardless of status?", False
        )

        if implot or psfplot:
            # define the panel grid. first get the labels and maximum
            # dimensions
            ccdinf = spooler.get_ccd_pars(source, resource)

            nxdef = cl.get_default("nx", 3)

            if len(ccdinf) > 1:
                ccd = cl.get_value("ccd", "CCD(s) to plot [0 for all]", "0")
                if ccd == "0":
                    ccds = list(ccdinf.keys())
                else:
                    ccds = ccd.split()

                if len(ccds) > 1:
                    nxdef = min(len(ccds), nxdef)
                    cl.set_default("nx", nxdef)
                    nx = cl.get_value("nx", "number of panels in X", 3, 1)
                else:
                    nx = 1
            else:
                nx = 1
                ccds = list(ccdinf.keys())

            # Some settings for the image plots
            cmap = cl.get_value(
                "cmap", "colour map to use ['none' for mpl default]", "Greys"
            )
            cmap = None if cmap == "none" else cmap

            # define the display intensities
            msub = cl.get_value("msub", "subtract median from each window?", True)

            iset = cl.get_value(
                "iset",
                "set intensity a(utomatically), d(irectly) or with p(ercentiles)?",
                "a",
                lvals=["a", "d", "p"],
            )

            plo, phi = 5, 95
            ilo, ihi = 0, 1000
            if iset == "d":
                ilo = cl.get_value("ilo", "lower intensity limit", 0.0)
                ihi = cl.get_value("ihi", "upper intensity limit", 1000.0)
            elif iset == "p":
                plo = cl.get_value(
                    "plo", "lower intensity limit percentile", 5.0, 0.0, 100.0
                )
                phi = cl.get_value(
                    "phi", "upper intensity limit percentile", 95.0, 0.0, 100.0
                )

            # arguments that set region to plot
            for i, cnam in enumerate(ccds):
                nxtot, nytot, nxpad, nypad = ccdinf[cnam]
                if i == 0:
                    xmin, xmax = float(-nxpad), float(nxtot + nxpad + 1)
                    ymin, ymax = float(-nypad), float(nytot + nypad + 1)
                else:
                    xmin = min(xmin, float(-nxpad))
                    xmax = max(xmax, float(nxtot + nxpad + 1))
                    ymin = min(ymin, float(-nypad))
                    ymax = max(ymax, float(nytot + nypad + 1))

            xlo = cl.get_value(
                "xlo", "left-hand X value", xmin, xmin, xmax, enforce=False
            )
            xhi = cl.get_value(
                "xhi", "right-hand X value", xmax, xmin, xmax, enforce=False
            )
            ylo = cl.get_value("ylo", "lower Y value", ymin, ymin, ymax, enforce=False)
            yhi = cl.get_value("yhi", "upper Y value", ymax, ymin, ymax, enforce=False)

        else:
            ccds, nx, msub, iset = None, None, None, None
            ilo, ihi, plo, phi = None, None, None, None
            xlo, xhi, ylo, yhi = None, None, None, None

        # save list of parameter values for writing to the reduction file
        plist = cl.list()

    ################################################################
    #
    # all the inputs have now been obtained. Get on with doing stuff

    # Set up the plot devices and buffers
    if lcplot:
        # lightcurve plot
        lpanel, xpanel, ypanel, tpanel, spanel = setup_lcplot(rfile)
        lbuffer, xbuffer, ybuffer, tbuffer, sbuffer = setup_lcplot_buffers(rfile)
    else:
        lpanel = None
        xpanel = None
        ypanel = None
        tpanel = None
        spanel = None
        lbuffer = None
        xbuffer = None
        ybuffer = None
        sbuffer = None
        tbuffer = None


    # Set up the multiprocessing pool if requested
    ncpu = rfile["general"]["ncpu"]
    if ncpu > 1:
        pool = multiprocessing.Pool(processes=ncpu)
    else:
        pool = None

    # Containers for the processed, debiassed and raw MCCD groups
    # and their frame numbers
    pccds, bccds, mccds, nframes = [], [], [], []
    tzero = None

    # get hipercam version to write into the reduce log file
    hipercam_version = hcam.version()

    # Initialise the plot managers
    # These both use the exact same base class, aside from `plot_psf_residuals`
    if implot:
        imanager = ImageManager(
            plot_psf_residuals=False,
            cnams=ccds,
            plotall=plotall,
            ncols=nx,
            iset=iset,
            ilim=(plo, phi) if iset == "p" else (ilo, ihi),
            region=(xlo, xhi, ylo, yhi),
            msub=msub,
            cmap=cmap,
            figsize=(imwidth, imheight),
            position=(imxpos, imypos),
            memory_args=(command, args) if memory else None,
        )
    if psfplot:
        psfmanager = ImageManager(
            plot_psf_residuals=True,
            cnams=ccds,
            plotall=plotall,
            ncols=nx,
            iset=iset,
            ilim=(plo, phi) if iset == "p" else (ilo, ihi),
            region=(xlo, xhi, ylo, yhi),
            msub=msub,
            cmap=cmap,
            figsize=(psfwidth, psfheight),
            position=(psfxpos, psfypos),
            memory_args=(command, args) if memory else None,
        )

    # Start the main loop
    total_time = 0.0
    with (
        suppress(KeyboardInterrupt),  # catch Ctrl-C to exit the loop cleanly
        spooler.data_source(source, resource, first, full=False) as spool,
        LogWriter(log, rfile, hipercam_version, plist) as logfile
    ):
        for n, mccd in enumerate(spool):
            if server_or_local:
                # Handle the waiting game ...
                # Includes some awkward stuff involving updating on a cycle
                # faster than twait to make the plots more responsive,
                # if twait is long.
                updaters = []
                if implot:
                    updaters.append(imanager.refresh)
                if psfplot:
                    updaters.append(psfmanager.refresh)

                give_up, try_again, total_time = spooler.hang_about(
                    mccd, twait, tmax, total_time, updaters, tupdate
                )

                if give_up:
                    break
                elif try_again:
                    continue

            # We have a frame!
            nframe = mccd.head.get("NFRAME", n + 1)

            if source != "hf" and last and nframe > last:
                # finite last frame number
                print("\nHave reduced up to the last frame set.")
                break

            # Print progress indicators
            tstamp = Time(mccd.head["TIMSTAMP"], format="isot", precision=3)
            tok = "ok" if mccd.head.get("GOODTIME", True) else "nok"
            print(
                f"Frame {nframe}: utc= {tstamp.iso} ({tok}), ",
                end="" if implot else "\n",
            )

            # Trim the frames: ULTRACAM windowed data has bad columns
            # and rows on the sides of windows closest to the readout
            # which can badly affect reduction. This option strips
            # them.
            if trim:
                hcam.ccd.trim_ultracam(mccd, ncol, nrow)

            # First time setup
            if n == 0:
                # This is the first frame, which allows us to make
                # some checks and initialisations.
                read, gain, ok = initial_checks(mccd, rfile)
                if not ok:
                    break

                # Choose between PSF and normal photometry
                if use_psf:
                    # create a process function by wrapping ccdproc
                    # in a partial whose first argument is the PSF extraction
                    # function
                    process_func = partial(ccdproc, extractFluxPSF)
                else:
                    # use a partial to encapsulate the normal extraction
                    process_func = partial(ccdproc, extractFlux)

                # Define the CCD processor function object
                processor = ProcessCCDs(rfile, read, gain, process_func, pool)

            # Lots of frame processing and calibration to do
            # From now on, we will be storing three copies of the MCCD:
            #   - 'pccd' is the fully processed data (debiassed, flat-fielded etc.)
            #   - 'bccd' is the debiassed data, used for variance computation
            #   - 'mccd' is the raw data, used to determine saturation

            # subtract the bias
            if rfile.bias is not None:
                bccd = mccd - rfile.bias
                bexpose = rfile.bias.head.get("EXPTIME", 0.0)
            else:
                bccd = mccd.copy()
                bexpose = 0.0
            pccd = bccd.copy()

            # subtract the dark, scaling by exposure time
            if rfile.dark is not None:
                dexpose = rfile.dark.head["EXPTIME"]
                if rfile.bias is not None:
                    bexpose = rfile.bias.head.get("EXPTIME", 0.0)
                else:
                    bexpose = 0.0
                for cnam in pccd:
                    ccd = pccd[cnam]
                    cexpose = ccd.head["EXPTIME"]
                    scale = (cexpose - bexpose) / dexpose
                    ccd -= scale * rfile.dark[cnam]

            # divide out the flat
            if rfile.flat is not None:
                pccd /= rfile.flat

            # attempt to correct for poorly placed frame transfer mask,
            # causing a step illumination in the y-direction
            # also includes a stage where we average in
            # the Y direction to try to eliminate high pixels
            if rfile["focal_mask"]["demask"]:
                # loop through all windows of all CCDs
                dthresh = rfile["focal_mask"]["dthresh"]
                for ccd in pccd.values():
                    for wind in ccd.values():
                        # form mean in Y direction, then try to
                        # mask out high pixels
                        ymean = np.mean(wind.data, 0)
                        xmask = ymean == ymean
                        while 1:
                            # rejection cycle, rejecting
                            # overly positive pixels
                            ave = ymean[xmask].mean()
                            rms = ymean[xmask].std()
                            diff = ymean - ave
                            diff[~xmask] = 0
                            imax = np.argmax(diff)
                            if diff[imax] > dthresh * rms:
                                xmask[imax] = False
                            else:
                                break

                        # form median in X direction
                        xmedian = np.median(wind.data[:, xmask], 1)

                        # subtract it's median to avoid removing
                        # general background
                        xmedian -= np.median(xmedian)

                        # now subtract from 2D image using
                        # broadcasting rules
                        wind.data -= xmedian.reshape((len(xmedian), 1))

            # remove fringes
            if rfile.fmap is not None:
                # apply only to CCDs present in both fmap and fpair
                for cnam in rfile.fmap:
                    if cnam in rfile.fpair:
                        ccd = pccd[cnam]
                        fscale = rfile.fpair[cnam].scale(
                            ccd,
                            rfile.fmap[cnam],
                            rfile["calibration"]["nhalf"],
                            rfile["calibration"]["rmin"],
                            rfile["calibration"]["rmax"],
                        )
                        ccd -= fscale * rfile.fmap[cnam]

            # Now we're ready to do the photometry.
            # Accumulate frames into processing groups for faster parallelisation
            pccds.append(pccd)
            bccds.append(bccd)
            mccds.append(mccd)
            nframes.append(nframe)

            # If we have enough frames, process them in parallel.
            # Otherwise we keep spooling for more until the group is full
            # (or we run out of frames and break out early).
            if len(pccds) < rfile["general"]["ngroup"]:
                # keep spooling for more frames
                continue

            # Carry out parallel processing (where all the fun stuff happens)
            results = processor(pccds, bccds, mccds, nframes)

            # Finally we're ready to start plotting
            # First the main image plot
            if implot:
                # Update the image plot
                # (note plotting the processed data)
                imanager.update(pccd, results)

                # Get statistics to print out
                message = f"exp= {mccd.head['EXPTIME']:.4f}"
                for cnam in ccds:
                    message += f", CCD {cnam}: "

                    if not mccd[cnam].is_data():
                        # skipped due to nskip > 0, no data in this frame
                        message += "none"
                        continue

                    # add the image limits
                    vmin, vmax = imanager.get_ilim(cnam)
                    message += f"{vmin:.1f} to {vmax:.1f}"

                # Print messages
                print(message)

            # The PSF plot
            if use_psf and psfplot:
                psfmanager.update(pccd, results)

            # The Lightcurve plot
            if lcplot:
                tzero = update_lcplot(
                    results,
                    rfile,
                    tzero,
                    tkeep,
                    lpanel,
                    xpanel,
                    ypanel,
                    tpanel,
                    spanel,
                    lbuffer,
                    xbuffer,
                    ybuffer,
                    tbuffer,
                    sbuffer,
                )

            # Write out results to the log file
            messages = logfile.write_results(results)

            # Print out any accumulated alert messages
            if len(messages):
                print("\n".join(messages))

            # Reset the frame buffers
            pccds, bccds, mccds, nframes = [], [], [], []

        # Out of the loop now.
        # If ngroup > 1, we might have some frames left over that haven't been
        # processed yet. If so, process them now.
        if len(mccds):
            # carry out parallel processing
            results = processor(pccds, bccds, mccds, nframes)

            # write out results to the log file
            messages = logfile.write_results(results)

            # print out any accumulated alert messages
            if len(messages):
                print("\n".join(messages))

            # update the plots with the new results
            if implot:
                imanager.update(pccd, results)
                # TODO: we don't print the image limits here (could be in update?)
            if use_psf and psfplot:
                psfmanager.update(pccd, results)
            if lcplot:
                tzero = update_lcplot(
                    results,
                    rfile,
                    tzero,
                    tkeep,
                    lpanel,
                    xpanel,
                    ypanel,
                    tpanel,
                    spanel,
                    lbuffer,
                    xbuffer,
                    ybuffer,
                    tbuffer,
                    sbuffer,
                )

    if implot or psfplot or lcplot:
        # At the end the plots will close automatically,
        # so block this by asking the user to confirm
        input("\nHit carriage return to close the plot(s): ")


class Panel:
    """
    Keeps track of the configuration of particular panels of plots so that
    they can be easily re-plotted and selected for additional plotting if
    need be.
    """

    def __init__(
        self,
        device,
        xv1,
        xv2,
        yv1,
        yv2,
        xlabel,
        ylabel,
        tlabel,
        xopt,
        yopt,
        x1,
        x2,
        y1,
        y2,
    ):
        """
        This takes all the arguments needs to set up some axes
        at an arbitrary location, using PGPLOT commands pgsvp, pgswin,
        pgbox and pglab. 'device' is the hipercam.pgp.Device to use
        for the plot. It only stores these values. 'plot' actually
        draws the axes.
        """
        self.device = device
        self.xv1 = xv1
        self.xv2 = xv2
        self.yv1 = yv1
        self.yv2 = yv2
        self.xlabel = xlabel
        self.ylabel = ylabel
        self.tlabel = tlabel
        self.xopt = xopt
        self.yopt = yopt
        self.x1 = x1
        self.x2 = x2
        self.y1 = y1
        self.y2 = y2

        # Plot it
        self.plot()

    def plot(self):
        """Plot the Panel. After running this you can plot to the Panel. If you plot
        to another Panel, you can return to this one using 'select'.

        """

        # select the device
        self.device.select()

        # draw the axes
        pgsci(hcam.pgp.Params["axis.ci"])
        pgsch(hcam.pgp.Params["axis.number.ch"])
        pgsvp(self.xv1, self.xv2, self.yv1, self.yv2)

        # avoid invalid limits warnings from PGPLOT
        if self.x1 == self.x2:
            x1, x2 = 0, 1
        else:
            x1, x2 = self.x1, self.x2
        if self.y1 == self.y2:
            y1, y2 = 0, 1
        else:
            y1, y2 = self.y1, self.y2
        pgswin(x1, x2, y1, y2)

        pgbox(self.xopt, 0, 0, self.yopt, 0, 0)

        # plot the labels
        pgsci(hcam.pgp.Params["axis.label.ci"])
        pgsch(hcam.pgp.Params["axis.label.ch"])
        pglab(self.xlabel, self.ylabel, self.tlabel)

    def select(self):
        """
        Selects this panel as the one to plot to. You can only use this if you
        have plotted the panel.
        """

        # select the device
        self.device.select()

        # set the physical scales and the viewport
        pgsvp(self.xv1, self.xv2, self.yv1, self.yv2)

        # avoid invalid limits warnings from PGPLOT
        if self.x1 == self.x2:
            x1, x2 = 0, 1.0
        else:
            x1, x2 = self.x1, self.x2
        if self.y1 == self.y2:
            y1, y2 = 0, 1.0
        else:
            y1, y2 = self.y1, self.y2
        pgswin(x1, x2, y1, y2)


def plotLight(panel, tzero, results, rfile, tkeep, lbuffer):
    """Plots one set of results in the light curve panel. Handles storage of
    points for future re-plots, computing new plot limits where needed.

    It returns a bool which if True means that there is a need to re-plot, and
    a maximum time of a plotted point for use in adjusting the X-axis.  The
    latter is returned as None if no plot is plotted.  This is deferred since
    there may be other panels to be adjusted as well since if a plot is
    cleared, everything has to be re-built.

    """

    # by default, don't re-plot
    replot = False

    skipbadt = rfile["general"]["skipbadt"]

    # shorthand
    sect = rfile["light"]

    # select the light curve panel
    panel.select()

    # Get the current y-range
    ymin, ymax = panel.y1, panel.y2
    if ymin > ymax:
        ymin, ymax = ymax, ymin

    # add points to the plot and buffers, tracking the minimum and
    # maximum values
    tmax = fmin = fmax = None
    for lc in lbuffer:
        tmax, fmin, fmax = lc.add_point(results, tzero, tmax, fmin, fmax, skipbadt)
        lc.trim(tkeep)

    if (
        not sect["y_fixed"]
        and fmin is not None
        and ((ymin == ymax) or (fmin < ymin or fmax > ymax))
    ):
        # we are going to have to replot because we have moved
        # outside the y-limits of the panel. We extend a little bit
        # more than necessary according to extend_y in order to
        # reduce the amount of such re-plotting
        replot = True

        if ymin == ymax:
            # First time through just use data
            extend = sect["extend_y"] * (fmax - fmin)
            # for one CCD, fmin==fmax after first frame,
            # and we never get out of ymin==ymax and the scale
            # is never reset
            if extend == 0:
                extend = 0.001 * fmax if sect["linear"] else 0.001
            ymin = fmin - extend
            ymax = fmax + extend
        else:
            # subsequently use the plot range
            extend = sect["extend_y"] * (ymax - ymin)
            if fmin < ymin:
                ymin = fmin - extend
            if fmax > ymax:
                ymax = fmax + extend

        if sect["linear"]:
            panel.y1, panel.y2 = ymin, ymax
        else:
            panel.y1, panel.y2 = ymax, ymin

    return (replot, tmax)


def plotPosition(xpanel, ypanel, tzero, results, rfile, tkeep, xbuffer, ybuffer):
    """Plots one set of results in the seeing panel. Handles storage of
    points for future re-plots, computing new plot limits where needed.

    It returns a bool which if True means that there is a need to re-plot.
    This is deferred since there may be other panels to be adjusted as well
    since if a plot is cleared, everything has to be re-built.
    """

    # by default, don't re-plot
    replot = False

    skipbadt = rfile["general"]["skipbadt"]

    # shorthand
    sect = rfile["position"]

    # select the X panel
    xpanel.select()

    # add points to the plot and buffers
    tmax = xmin = xmax = None
    for xpos in xbuffer:
        tmax, xmin, xmax = xpos.add_point(results, tzero, tmax, xmin, xmax, skipbadt)
        xpos.trim(tkeep)

    if (
        xmin is not None
        and (xmin < xpanel.y1 or xmax > xpanel.y2)
        and not sect["x_fixed"]
    ):
        replot = True
        extend = sect["extend_y"] * (xpanel.y2 - xpanel.y1)
        if xmin < xpanel.y1:
            xpanel.y1 = xmin - extend

        if xmax > xpanel.y2:
            xpanel.y2 = xmax + extend

    # select the panel
    ypanel.select()

    # add points to the plot and buffers
    ymin = ymax = None
    for ypos in ybuffer:
        tmax, ymin, ymax = ypos.add_point(results, tzero, tmax, ymin, ymax, skipbadt)
        ypos.trim(tkeep)

    if (
        ymin is not None
        and (ymin < ypanel.y1 or ymax > ypanel.y2)
        and not sect["y_fixed"]
    ):
        replot = True
        extend = sect["extend_y"] * (ypanel.y2 - ypanel.y1)
        if ymin < ypanel.y1:
            ypanel.y1 = ymin - extend

        if ymax > ypanel.y2:
            ypanel.y2 = ymax + extend

    return (replot, tmax)


