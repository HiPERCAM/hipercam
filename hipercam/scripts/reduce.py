def setup_lcplot(rfile):
    """Perform initial setup of the lightcurve plot for reduction outputs."""
    device = hcam.pgp.Device(rfile["general"]["ldevice"])
    lwidth = rfile["general"]["lwidth"]
    lheight = rfile["general"]["lheight"]
    if lwidth > 0 and lheight > 0:
        pgpap(lwidth, lheight / lwidth)

    # define and draw panels. 'total' is the total height of all
    # panel which will be used to work out the fraction occupied
    # by each one. There is always a light curve panel of unit
    # height.
    lheight = 1.0
    total = lheight

    if rfile.position:
        pheight = rfile["position"]["height"]
        total += pheight

    if rfile.transmission:
        theight = rfile["transmission"]["height"]
        total += theight

    if rfile.seeing:
        sheight = rfile["seeing"]["height"]
        total += sheight

    # define standard viewport. We set the character height to ensure
    # there is enough room around the edges.
    pgsch(max(hcam.pgp.Params["axis.label.ch"], hcam.pgp.Params["axis.number.ch"]))
    pgvstd()
    xv1, xv2, yv1, yv2 = pgqvp()
    x1, x2 = 0, rfile["lcplot"]["extend_x"]

    # scale = vertical height of LC panel in device coordinates
    scale = (yv2 - yv1) / total

    # Work from the bottom up to get the X-axis labelling right
    # since it has to be turned off for the upper panels.  at each
    # step yv1, yv2 is the Panel's vertical range
    xlabel = "Time [mins]"
    xopt = "bcnst"

    if rfile.seeing:
        # the seeing panel
        yv2 = yv1 + scale * sheight
        spanel = Panel(
            device,
            xv1,
            xv2,
            yv1,
            yv2,
            xlabel,
            'FWHM (")',
            "",
            xopt,
            "bcnst",
            x1,
            x2,
            0,
            rfile["seeing"]["ymax"],
        )

        xlabel = ""
        xopt = "bcst"
        yv1 = yv2
    else:
        spanel = None

    if rfile.transmission:
        # the transmission panel
        yv2 = yv1 + scale * theight
        tpanel = Panel(
            device,
            xv1,
            xv2,
            yv1,
            yv2,
            xlabel,
            "% trans",
            "",
            xopt,
            "bcnst",
            x1,
            x2,
            0,
            rfile["transmission"]["ymax"],
        )

        xlabel = ""
        xopt = "bcst"
        yv1 = yv2
    else:
        tpanel = None

    if rfile.position:
        # the X,Y position panels. First Y
        yv2 = yv1 + scale * pheight / 2.0
        ypanel = Panel(
            device,
            xv1,
            xv2,
            yv1,
            yv2,
            xlabel,
            "Y",
            "",
            xopt,
            "bcnst",
            x1,
            x2,
            rfile["position"]["y_min"],
            rfile["position"]["y_max"],
        )

        xlabel = ""
        xopt = "bcst"
        yv1 = yv2

        # then X
        yv2 = yv1 + scale * pheight / 2.0
        xpanel = Panel(
            device,
            xv1,
            xv2,
            yv1,
            yv2,
            xlabel,
            "X",
            "",
            xopt,
            "bcnst",
            x1,
            x2,
            rfile["position"]["x_min"],
            rfile["position"]["x_max"],
        )

        xlabel = ""
        xopt = "bcst"
        yv1 = yv2
    else:
        xpanel = None
        ypanel = None

    # Light curve is not an option and is always at the top
    yv2 = yv1 + scale * lheight

    lpanel = Panel(
        device,
        xv1,
        xv2,
        yv1,
        yv2,
        xlabel,
        "Flux" if rfile["light"]["linear"] else "Magnitudes",
        "",
        xopt,
        "bcnst",
        x1,
        x2,
        rfile["light"]["y1"],
        rfile["light"]["y2"],
    )

    return lpanel, xpanel, ypanel, tpanel, spanel


def setup_lcplot_buffers(rfile):
    """Create buffers to store the points plotted in each panel."""
    lbuffer = []
    for plot_config in rfile["light"]["plot"]:
        lbuffer.append(LightCurve(plot_config, rfile["light"]["linear"]))

    xbuffer, ybuffer = [], []
    if rfile.position:
        for plot_config in rfile["position"]["plot"]:
            xbuffer.append(Xposition(plot_config))
            ybuffer.append(Yposition(plot_config))

    tbuffer = []
    if rfile.transmission:
        for plot_config in rfile["transmission"]["plot"]:
            tbuffer.append(Transmission(plot_config))

    sbuffer = []
    if rfile.seeing:
        for plot_config in rfile["seeing"]["plot"]:
            sbuffer.append(Seeing(plot_config, rfile["general"]["scale"]))

    return lbuffer, xbuffer, ybuffer, tbuffer, sbuffer


def update_lcplot(
    results,
    rfile,
    tzero,
    tkeep,
    lpanel,
    xpanel,
    ypanel,
    tpanel,
    spanel,
    lbuffer,
    xbuffer,
    ybuffer,
    tbuffer,
    sbuffer,
):
    """Plot updater routine for lightcurve plot.

    Arguments::

        results : list
            contains tuples with the results for groups of frames for each CCD.
            See LogWriter.write for more details on its structure.

        rfile : Rfile
              reduce file parameters

        tzero : float
            reference time for plotting

        tkeep : float
            time to keep in the plot window

        lpanel, xpanel, ypanel, tpanel, spanel : Panel
            plot panels for lightcurve, x position, y position, transmission and seeing

        lbuffer, xbuffer, ybuffer, tbuffer, sbuffer : list
            buffers for lightcurve, x position, y position, transmission and seeing

    """
    if tzero is None:
        # first set the tzero if it is not set yet

        skipbadt = rfile["general"]["skipbadt"]
        for cnam, res in results:
            for (
                nframe,
                store,
                ccdaper,
                reses,
                mjdint,
                mjdfrac,
                mjdok,
                expose,
            ) in res:
                if mjdok or not skipbadt:
                    tzero = mjdint + mjdfrac

    if tzero is None:
        # Must have a tzero to get going at all
        return None

    # track the maximum time
    tmax = None

    replot, ltmax = plotLight(lpanel, tzero, results, rfile, tkeep, lbuffer)
    tmax = tmax if ltmax is None else ltmax if tmax is None else max(tmax, ltmax)

    if rfile.position:
        # plot the positions
        rep, ptmax = plotPosition(
            xpanel, ypanel, tzero, results, rfile, tkeep, xbuffer, ybuffer
        )
        replot |= rep
        tmax = (
            tmax if ptmax is None else ptmax if tmax is None else max(tmax, ptmax)
        )

    if rfile.transmission:
        # plot the transmission
        rep, ttmax = plotTrans(tpanel, tzero, results, rfile, tkeep, tbuffer)
        replot |= rep
        tmax = (
            tmax if ttmax is None else ttmax if tmax is None else max(tmax, ttmax)
        )

    if rfile.seeing:
        # plot the seeing
        rep, stmax = plotSeeing(spanel, tzero, results, rfile, tkeep, sbuffer)
        replot |= rep
        tmax = (
            tmax if stmax is None else stmax if tmax is None else max(tmax, stmax)
        )

    # check the time
    if tmax is not None and tmax > lpanel.x2:
        # extend range by multiple of extend_x
        x2 = lpanel.x2
        while tmax > x2:
            x2 += rfile["lcplot"]["extend_x"]

        # need to re-plot
        replot = True
        lpanel.x2 = x2

        if rfile.position:
            xpanel.x2 = x2
            ypanel.x2 = x2

        if rfile.transmission:
            tpanel.x2 = x2

        if rfile.seeing:
            spanel.x2 = x2

    if replot:
        # re-plot.

        if tkeep > 0:
            # adjust start time if tkeep in use
            tstart = max(0, lpanel.x2 - tkeep)

            lpanel.x1 = tstart

            if rfile.position:
                xpanel.x1 = tstart
                ypanel.x1 = tstart

            if rfile.transmission:
                tpanel.x1 = tstart

            if rfile.seeing:
                spanel.x1 = tstart

        # start buffering
        pgbbuf()

        # erase plot
        pgeras()

        # re-draw the light curve panel
        lpanel.plot()

        for lc in lbuffer:
            # convert the buffered data into float32 ndarrays
            t = np.array(lc.t, dtype=np.float32)
            f = np.array(lc.f, dtype=np.float32)
            fe = np.array(lc.fe, dtype=np.float32)
            symbs = np.array(lc.symb, dtype=np.int32)
            asymbs = set(symbs)

            # Plot the error bars
            if lc.ecol is not None:
                pgsci(lc.ecol)
                pgerry(t, f - fe, f + fe, 0)

            # Plot the data
            pgsci(lc.dcol)
            pgsch(0.5)
            for symb in asymbs:
                ok = symbs == symb
                pgpt(t[ok], f[ok], symb)

        if rfile.position:
            # re-draw the position panels

            xpanel.plot()
            for xpos in xbuffer:
                # convert the buffered data into float32 ndarrays
                t = np.array(xpos.t, dtype=np.float32)
                f = np.array(xpos.f, dtype=np.float32)
                fe = np.array(xpos.fe, dtype=np.float32)
                symbs = np.array(xpos.symb, dtype=np.int32)
                asymbs = set(symbs)

                # Plot the error bars
                if xpos.ecol is not None:
                    pgsci(xpos.ecol)
                    pgerry(t, f - fe, f + fe, 0)

                # Plot the data
                pgsci(xpos.dcol)
                pgsch(0.5)
                for symb in asymbs:
                    ok = symbs == symb
                    pgpt(t[ok], f[ok], symb)

            ypanel.plot()
            for ypos in ybuffer:
                # convert the buffered data into float32 ndarrays
                t = np.array(ypos.t, dtype=np.float32)
                f = np.array(ypos.f, dtype=np.float32)
                fe = np.array(ypos.fe, dtype=np.float32)
                symbs = np.array(ypos.symb, dtype=np.int32)
                asymbs = set(symbs)

                # Plot the error bars
                if ypos.ecol is not None:
                    pgsci(ypos.ecol)
                    pgerry(t, f - fe, f + fe, 0)

                # Plot the data
                pgsci(ypos.dcol)
                pgsch(0.5)
                for symb in asymbs:
                    ok = symbs == symb
                    pgpt(t[ok], f[ok], symb)

        if rfile.transmission:
            # re-draw the transmission panel
            tpanel.plot()

            for trans in tbuffer:
                if trans.fmax:
                    # convert the buffered data into float32
                    # ndarrays
                    t = np.array(trans.t, dtype=np.float32)
                    f = np.array(trans.f, dtype=np.float32)
                    fe = np.array(trans.fe, dtype=np.float32)
                    scale = np.float32(100.0 / trans.fmax)
                    f *= scale
                    fe *= scale
                    symbs = np.array(trans.symb, dtype=np.int32)
                    asymbs = set(symbs)

                    # Plot the error bars
                    if trans.ecol is not None:
                        pgsci(trans.ecol)
                        pgerry(t, f - fe, f + fe, 0)

                    # Plot the data
                    pgsci(trans.dcol)
                    pgsch(0.5)
                    for symb in asymbs:
                        ok = symbs == symb
                        pgpt(t[ok], f[ok], symb)

        if rfile.seeing:
            # re-draw the seeing panel
            spanel.plot()

            for see in sbuffer:
                # convert the buffered data into float32 ndarrays
                t = np.array(see.t, dtype=np.float32)
                f = np.array(see.f, dtype=np.float32)
                fe = np.array(see.fe, dtype=np.float32)
                symbs = np.array(see.symb, dtype=np.int32)
                asymbs = set(symbs)

                # Plot the error bars
                if see.ecol is not None:
                    pgsci(see.ecol)
                    pgerry(t, f - fe, f + fe, 0)

                # Plot the data
                pgsci(see.dcol)
                pgsch(0.5)
                for symb in asymbs:
                    ok = symbs == symb
                    pgpt(t[ok], f[ok], symb)

        # end buffering
        pgebuf()

    return tzero


class ImageManager(hcam.mpl.AnimationManager):
    """Class to control the image animation.

    The same class is used for the Image and PSF residual plots, using the
    `plot_psf_residuals` flag to control which is displayed.

    Initialising it creates and opens the empty figure.

    After that, call ``update`` once per frame to update the artists,
    and ``refresh`` as often as needed to keep the window responsive.

    """

    def __init__(
        self,
        plot_psf_residuals,
        cnams,
        plotall,
        ncols,
        iset,
        ilim,
        region,
        msub,
        cmap,
        figsize,
        position,
        memory_args,
    ):
        """Initialises and manages the plot.

        Arguments:

        plot_psf_residuals : bool
            If True, plot the residuals of the PSF fit instead of the CCD data.
            Requires there to be PSF fit results in the `results` argument
            passed to `update()`, meaining ProcessCCDs must have been called
            using `extractFluxPSF` as the process function.

        cnams : list of str
            The names of the CCDs to plot.

        plotall : bool
            If True, plot all frames, even if they contain no data.

        ncols : int
            The number of columns in the grid of subplots

        iset : str
            How to set the intensity scale for the images:
                'a' for automatic min/max range
                'p' for percentiles (set using `ilim`)
                'd' for direct values (set using `ilim`)

        ilim : tuple[float, float] | None
            Lower and upper limits for the intensity scaling.

        region : tuple[int, int, int, int] | None
            The region to plot, values are (xmin, xmax, ymin, ymax)
            If None, the entire CCD is displayed.
            If iset='p', only this region is used to compute the percentiles for
            intensity scaling.

        msub : bool
            If True, subtract the median value from each window before plotting.
            Is ignored if `plot_psf_residuals` is True.

        cmap : str  | None
            Matplotlib colour map. None gives default

        figsize : tuple[float, float] | None
            The width and height of the figure, in inches.
            If None, the default size is used.

        position : tuple[int, int] | None
            The position of the figure window on the screen, in pixels.
            If None, the default position is used.

        memory_args : tuple[str, list] | None
            If not None, the first element is the command name and the second
            is the list of arguments. The window geometry will be saved to the
            command's Cline file on close, and restored on next run.

        """
        # create empty figure and axes
        self.fig, self.axs = hcam.mpl.create_figure(
            cnams=cnams,
            ncols=ncols,
            region=region,
            title="CCD display" if not plot_psf_residuals else "PSF residuals",
            figsize=figsize,
            position=position,
        )

        # initialise the animation manager with the figure
        super().__init__(self.fig)

        # inputs for the image plots
        self.plot_psf_residuals = plot_psf_residuals
        self.cnams = cnams
        self.plotall = plotall
        self.iset = iset
        self.ilim = ilim
        self.region = region
        self.msub = msub
        self.cmap = cmap

        # holding dict for aperture artists
        self.aper_artists = {}

        # save window geometry on close
        if memory_args:
            def save_geometry(event):
                prefix = "psf" if self.plot_psf_residuals else "im"
                imwidth, imheight, imxpos, imypos = hcam.mpl.store_window(
                    self.fig, memory_args[0], memory_args[1], prefix=prefix
                )
                print(
                    f"{'Image' if not self.plot_psf_residuals else 'PSF residuals'}"
                    " display memory updated [memory=True]:",
                    f"{prefix}width={imwidth:.1f}, {prefix}height={imheight:.1f}, "
                    f"{prefix}xpos={imxpos}, {prefix}ypos={imypos}"
                )
            self.fig.canvas.mpl_connect("close_event", save_geometry)

        # open the plot
        self.show()

    def draw_artists(self):
        """Draw all of the animated artists."""
        # Draw the CCD artists
        for cnam in self.artists:
            # each CCD has a dictionary of artists (returned by pCcd)
            for artists in self.artists[cnam].values():
                for artist in artists:
                    self.fig.draw_artist(artist)

        # Draw the aperture artists
        for cnam in self.aper_artists:
            # each CCD has a dictionary of artists (returned by pCcdAper)
            for artists in self.aper_artists[cnam].values():
                for artist in artists:
                    self.fig.draw_artist(artist)

    def update(self, mccd, results):
        """Create or update the artists with new data.

        Arguments :

        mccd : :class:`MCCD`
            The frame to display.

        results : list
            The results for the frame, as returned by ProcessCCDs.
            If `plot_psf_residuals` is True, the results must contain PSF fit results
            for each CCD, otherwise the residuals cannot be computed.

        """
        # TODO: results should just be a dict, or some nicer data structure?
        results = dict(results)

        # Update the artists for the CCDs
        self._update_images(mccd, results)

        # Update the artists for the apertures
        self._update_apertures(results)

        # Refresh the display
        self.refresh(redraw=True)

    def _update_images(self, mccd, results):
        """Create or update the CCD artists."""
        # Keep track of if new artists are created
        new_artists = False

        for cnam in self.cnams:
            if not mccd[cnam].is_data() and not self.plotall:
                # no new frame, just keep any existing artists (unless plotall is True)
                continue

            if not self.plot_psf_residuals:
                # Normal case, plot the CCD data
                ccd = mccd[cnam].copy()

                # subtract median from each window
                if self.msub:
                    for wind in ccd.values():
                        wind -= wind.median()

            else:
                # PSFplot case, plot the residuals of the PSF fit
                if cnam not in results:
                    # no new result, just keep any existing artists
                    continue

                # we always use the last result in the parallel group
                last_res = results[cnam][-1]
                psf_store = last_res[1]
                psf_model, box_wnam, box_limits = psf_store.get(
                    f"psf_model_{cnam}", None
                )

                if psf_model is None:
                    # no PSF model in the results, just keep any existing artists
                    continue

                ccd = mccd[cnam].copy()

                # find the indices of the stamp used for PSF photometry
                window = ccd[box_wnam]
                x1, x2, y1, y2 = box_limits
                # code copied from window class
                winh = super(hcam.Window, window).window(x1, x2, y1, y2)
                ix1 = (winh.llx - window.llx) // window.xbin
                iy1 = (winh.lly - window.lly) // window.ybin
                iy2 = iy1 + winh.ny
                ix2 = ix1 + winh.nx

                # extract a view of the data array
                data = window.data[iy1:iy2, ix1:ix2]
                resid = psf_model.make_residual_image(data)
                ccd[box_wnam].data[iy1:iy2, ix1:ix2] = resid

            # get scale limits
            vmin, vmax = hcam.mpl.get_scale_limits(
                ccd,
                mode=self.iset,
                limits=self.ilim,
                region=self.region,
            )

            # plot the CCD residuals
            if cnam not in self.artists:
                new_artists = True
            self.artists[cnam] = hcam.mpl.pCcd(
                ax=self.axs[cnam],
                ccd=ccd,
                vmin=vmin,
                vmax=vmax,
                cmap=self.cmap,
                tlabel=f"CCD {cnam}",
                animated=True,
                artists=self.artists[cnam] if cnam in self.artists else None,
                )

        if new_artists:
            # In this case we are setting up for the first time
            # We need to set the layout and re-draw to avoid irritating distorted images
            self.fig.tight_layout()
            self.fig.canvas.draw()

    def _update_apertures(self, results):
        """Create or update the aperture artists."""
        # TODO: Don't plot apertures if ccd.is_data() is False (for plotall=True)?
        for cnam in self.cnams:
            if cnam not in results:
                # no new result, just keep any existing artists
                continue

            # we always use the last result in the parallel group
            last_res = results[cnam][-1]
            ccd_aper = last_res[2]

            # plot all the apertures for this CCD
            self.aper_artists[cnam] = hcam.mpl.pCcdAper(
                ax=self.axs[cnam],
                ccdAper=ccd_aper,
                animated=True,
                artists=self.aper_artists[cnam] if cnam in self.aper_artists else None,
            )

    def get_ilim(self, cnam):
        """Returns the current intensity limits for the specified CCD."""
        if self.artists[cnam] is None:
            return None
        imgs = self.axs[cnam].get_images()
        return imgs[0].get_clim()  # for the first window, but should be the same
