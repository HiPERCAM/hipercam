########################################################
#
# ftargets --uses sep to find targets in a set of images
#
########################################################


def ftargets(args=None):
    """``ftargets [source device width height] (run first [twait tmax] |
    flist) trim ([ncol nrow]) (ccd (nx)) [pause] thresh fwhm minpix
    output bias flat msub iset (ilo ihi | plo phi) xlo xhi ylo yhi``

    This script carries out the following steps for each of a series
    of images:

      (1) detects the sources,
      (2) identifies isolated targets suited to profile fits,
      (3) fits 2D Moffat profiles to these,
      (4) Saves results to disk.

    The profile fits are carried out because `sep` does not return
    anything that can be used reliably for a FWHM.

    Several parameters depends on the object detection threshold
    retuned by the source detection. This is referred to as
    `threshold`. The source detection is carried out using `sep` which
    runs according to the usual source extractor algorithm of Bertin.

    The script plots the frames, with ellipses at 3*a,3*b indicated in
    red, green boxes indicating the range of pixels identified by
    `sep`, and blue boxes marking the targets selected for FWHM
    fitting (the boxes indicate the fit region).


    Parameters:

        source : string [hidden]
           Data source, five options for built-in sources:

             |  'hs' : HiPERCAM server
             |  'hl' : local HiPERCAM FITS file
             |  'us' : ULTRACAM server
             |  'ul' : local ULTRACAM .xml/.dat files
             |  'hf' : list of HiPERCAM hcm FITS-format files

           'hf' is used to look at sets of frames generated by 'grab'
           or converted from foreign data formats. The standard
           start-off default for ``source`` can be set using the
           environment variable HIPERCAM_DEFAULT_SOURCE. e.g. in bash
           :code:`export HIPERCAM_DEFAULT_SOURCE="us"` would ensure it
           always started with the ULTRACAM server by default. If
           unspecified, it defaults to 'hl'.

           Any instruments installed via plugins can be used as a source by
           specifying either ``<instrument>:local`` or ``<instrument>:server``.

        device : string [hidden]
          Plot device. PGPLOT is used so this should be a PGPLOT-style name,
          e.g. '/xs', '1/xs' etc. At the moment only ones ending /xs are
          supported.

        width : float [hidden]
           plot width (inches). Set = 0 to let the program choose.

        height : float [hidden]
           plot height (inches). Set = 0 to let the program choose. BOTH width
           AND height must be non-zero to have any effect

        run : string [if source ends 's' or 'l']
           run number to access, e.g. 'run034'

        flist : string [if source ends 'f']
           name of file list

        first : int [if source ends 's' or 'l']
           exposure number to start from. 1 = first frame; set = 0 to always
           try to get the most recent frame (if it has changed).  For data
           from the |hiper| server, a negative number tries to get a frame not
           quite at the end.  i.e. -10 will try to get 10 from the last
           frame. This is mainly to sidestep a difficult bug with the
           acquisition system.

        twait : float [if source ends 's' or 'l'; hidden]
           time to wait between attempts to find a new exposure, seconds.

        tmax : float [if source ends 's' or 'l'; hidden]
           maximum time to wait between attempts to find a new exposure,
           seconds.

        trim : bool [if source starts with 'u']
           True to trim columns and/or rows off the edges of windows nearest
           the readout which can sometimes contain bad data.

        ncol : int [if trim, hidden]
           Number of columns to remove (on left of left-hand window, and right
           of right-hand windows)

        nrow : int [if trim, hidden]
           Number of rows to remove (bottom of windows)

        ccd : string
           CCD(s) to plot, '0' for all, '1 3' to plot '1' and '3' only, etc.

        nx : int [if more than 1 CCD]
           number of panels across to display.

        pause : float [hidden]
           seconds to pause between frames (defaults to 0). This is in addition
           to any time taken per frame to read and display it, so is just to slow
           things not to set an exact rate.

        tupdate : float [hidden]
           target number of seconds between plot updates. This is to
           make the plots more responsive and get round issues with
           plots freezing until the next frame comes through which can
           be especially annoying with virtual desktops. Experiments
           with ULTRACAM@NTT indicated 0.2 to 0.6 secs or so works OK.
           Main impact seems to be on drpc CPU.

        thresh : float
           threshold (mutiple of RMS) to use for object detection. Typical
           values 2.5 to 4. The higher it is, the fewer objects will be located,
           but the fewer false detections will be made.

        fwhm : float
           FWHM to use for smoothing during object detection. Should be
           comparable to the seeing.

        minpix : int
           Minimum number of pixels above threshold before convolution to count
           as a detection. Useful in getting rid of cosmics and high dark count
           pixels.

        rmin : float
           Closest distance of any other detected object for an attempt
           to be made to fit the FWHM of an object [unbinned pixels].

        pmin : float
           Minimum peak height for an attempt to be made to fit the
           FWHM of an object. This should be a multiple of the object
           detection threshold (returned by `sep` for each object).

        pmax : float
           Maximum peak height for an attempt to be made to fit the
           FWHM of an object. Use to exclude saturated targets
           [counts]

        emax : float
           Maximum elongation (major/minor axis ratio = a/b), > 1. Use
           to reduce very non-stellar profiles.

        nmax : int
           Maximum number of FWHMs to measure. Will take the brightest first,
           judging by the flux.

        bias : string
           Name of bias frame to subtract, 'none' to ignore.

        flat : string
           Name of flat field to divide by, 'none' to ignore. Should normally
           only be used in conjunction with a bias, although it does allow you
           to specify a flat even if you haven't specified a bias.

        output: string
           Name of file for storage of results. Will be a fits file, with
           results saved to the HDU 1 as a table.

        iset : string [single character]
           determines how the intensities are determined. There are three
           options: 'a' for automatic simply scales from the minimum to the
           maximum value found on a per CCD basis. 'd' for direct just takes
           two numbers from the user. 'p' for percentile dtermines levels
           based upon percentiles determined from the entire CCD on a per CCD
           basis.

        ilo : float [if iset='d']
           lower intensity level

        ihi : float [if iset='d']
           upper intensity level

        plo : float [if iset='p']
           lower percentile level

        phi : float [if iset='p']
           upper percentile level

        xlo : float
           left-hand X-limit for plot

        xhi : float
           right-hand X-limit for plot (can actually be < xlo)

        ylo : float
           lower Y-limit for plot

        yhi : float
           upper Y-limit for plot (can be < ylo)

    """

    command, args = cline.script_args(args)

    # get the inputs
    with Cline("HIPERCAM_ENV", ".hipercam", command, args) as cl:

        # register parameters
        cl.register("source", Cline.GLOBAL, Cline.HIDE)
        cl.register("device", Cline.LOCAL, Cline.HIDE)
        cl.register("cmap", Cline.LOCAL, Cline.HIDE)
        cl.register("width", Cline.LOCAL, Cline.HIDE)
        cl.register("height", Cline.LOCAL, Cline.HIDE)
        cl.register("run", Cline.GLOBAL, Cline.PROMPT)
        cl.register("first", Cline.LOCAL, Cline.PROMPT)
        cl.register("trim", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ncol", Cline.GLOBAL, Cline.HIDE)
        cl.register("nrow", Cline.GLOBAL, Cline.HIDE)
        cl.register("twait", Cline.LOCAL, Cline.HIDE)
        cl.register("tmax", Cline.LOCAL, Cline.HIDE)
        cl.register("flist", Cline.LOCAL, Cline.PROMPT)
        cl.register("ccd", Cline.LOCAL, Cline.PROMPT)
        cl.register("nx", Cline.LOCAL, Cline.PROMPT)
        cl.register("pause", Cline.LOCAL, Cline.HIDE)
        cl.register("tupdate", Cline.LOCAL, Cline.HIDE)
        cl.register("thresh", Cline.LOCAL, Cline.PROMPT)
        cl.register("fwhm", Cline.LOCAL, Cline.PROMPT)
        cl.register("minpix", Cline.LOCAL, Cline.PROMPT)
        cl.register("rmin", Cline.LOCAL, Cline.PROMPT)
        cl.register("pmin", Cline.LOCAL, Cline.PROMPT)
        cl.register("pmax", Cline.LOCAL, Cline.PROMPT)
        cl.register("emax", Cline.LOCAL, Cline.PROMPT)
        cl.register("nmax", Cline.LOCAL, Cline.PROMPT)
        cl.register("rejthresh", Cline.LOCAL, Cline.PROMPT)
        cl.register("bias", Cline.GLOBAL, Cline.PROMPT)
        cl.register("flat", Cline.GLOBAL, Cline.PROMPT)
        cl.register("output", Cline.LOCAL, Cline.PROMPT)
        cl.register("iset", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ilo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ihi", Cline.GLOBAL, Cline.PROMPT)
        cl.register("plo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("phi", Cline.LOCAL, Cline.PROMPT)
        cl.register("xlo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("xhi", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ylo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("yhi", Cline.GLOBAL, Cline.PROMPT)

        # get inputs
        default_source = os.environ.get('HIPERCAM_DEFAULT_SOURCE','hl')
        source = cl.get_value(
            "source",
            "data source [hs, hl, us, ul, hf, or <instrument>:local/<instrument>:server]",
            default_source,
            lvals=available_instruments(),
        )

        # set some flags
        server_or_local = source.endswith("s") or source.endswith("l")

        # plot device stuff
        device = cl.get_value("device", "plot device", "1/xs")
        cmap = cl.get_value(
            "cmap", "colour map to use ['none' for mpl default]", "Greys"
        )
        width = cl.get_value("width", "plot width (inches)", 0.0)
        height = cl.get_value("height", "plot height (inches)", 0.0)

        if server_or_local:
            resource = cl.get_value("run", "run name", "run005")
            if source == "hs":
                first = cl.get_value("first", "first frame to plot", 1)
            else:
                first = cl.get_value("first", "first frame to plot", 1, 0)

            twait = cl.get_value(
                "twait", "time to wait for a new frame [secs]", 1.0, 0.0
            )
            tmax = cl.get_value(
                "tmax", "maximum time to wait for a new frame [secs]", 10.0, 0.0
            )

        else:
            resource = cl.get_value(
                "flist", "file list", cline.Fname("files.lis", hcam.LIST)
            )
            first = 1

        trim = cl.get_value("trim", "do you want to trim edges of windows?", True)
        if trim:
            ncol = cl.get_value("ncol", "number of columns to trim from windows", 0)
            nrow = cl.get_value("nrow", "number of rows to trim from windows", 0)

        # define the panel grid. first get the labels and maximum dimensions
        ccdinf = spooler.get_ccd_pars(source, resource)

        nxdef = cl.get_default("nx", 3)

        if len(ccdinf) > 1:
            ccd = cl.get_value("ccd", "CCD(s) to plot [0 for all]", "0")
            if ccd == "0":
                ccds = list(ccdinf.keys())
            else:
                ccds = ccd.split()
                check = set(ccdinf.keys())
                if not set(ccds) <= check:
                    raise hcam.HipercamError("At least one invalid CCD label supplied")

            if len(ccds) > 1:
                nxdef = min(len(ccds), nxdef)
                cl.set_default("nx", nxdef)
                nx = cl.get_value("nx", "number of panels in X", 3, 1)
            else:
                nx = 1
        else:
            nx = 1
            ccds = list(ccdinf.keys())

        cl.set_default("pause", 0.0)
        pause = cl.get_value(
            "pause", "time delay to add between" " frame plots [secs]", 0.0, 0.0
        )

        tupdate = cl.get_value(
            "tupdate", "target time between plot updates [secs]", 0.2, 0.01
        )

        thresh = cl.get_value("thresh", "source detection threshold [RMS]", 3.0)
        fwhm = cl.get_value("fwhm", "FWHM for source detection [binned pixels]", 4.0)
        minpix = cl.get_value("minpix", "minimum number of pixels above threshold", 3)
        rmin = cl.get_value(
            "rmin", "nearest neighbour for FWHM fits [unbinned pixels]", 20.0
        )
        pmin = cl.get_value(
            "pmin", "minimum peak value for profile fits [multiple of threshold]", 5.0
        )
        pmax = cl.get_value(
            "pmax", "maximum peak value for profile fits [counts]", 60000.0
        )
        emax = cl.get_value(
            "emax", "maximum elongation (a/b) for profile fits", 1.2, 1.0
        )
        nmax = cl.get_value("nmax", "maximum number of profile fits per window", 10, 1)
        rejthresh = cl.get_value(
            "rejthresh", "RMS rejection threshold for sky fitting", 4.0
        )

        # bias frame (if any)
        bias = cl.get_value(
            "bias",
            "bias frame ['none' to ignore]",
            cline.Fname("bias", hcam.HCAM),
            ignore="none",
        )
        if bias is not None:
            # read the bias frame
            bias = hcam.MCCD.read(bias)
            fprompt = "flat frame ['none' to ignore]"
        else:
            fprompt = "flat frame ['none' is normal choice with no bias]"

        # flat (if any)
        flat = cl.get_value(
            "flat", fprompt, cline.Fname("flat", hcam.HCAM), ignore="none"
        )
        if flat is not None:
            # read the flat frame
            flat = hcam.MCCD.read(flat)

        output = cl.get_value(
            "output",
            "output file for results",
            cline.Fname("sources", hcam.SEP, cline.Fname.NEW),
        )

        iset = cl.get_value(
            "iset",
            "set intensity a(utomatically)," " d(irectly) or with p(ercentiles)?",
            "a",
            lvals=["a", "d", "p"],
        )
        iset = iset.lower()

        plo, phi = 5, 95
        ilo, ihi = 0, 1000
        if iset == "d":
            ilo = cl.get_value("ilo", "lower intensity limit", 0.0)
            ihi = cl.get_value("ihi", "upper intensity limit", 1000.0)
        elif iset == "p":
            plo = cl.get_value(
                "plo", "lower intensity limit percentile", 5.0, 0.0, 100.0
            )
            phi = cl.get_value(
                "phi", "upper intensity limit percentile", 95.0, 0.0, 100.0
            )

        # region to plot
        for i, cnam in enumerate(ccds):
            nxtot, nytot, nxpad, nypad = ccdinf[cnam]
            if i == 0:
                xmin, xmax = float(-nxpad), float(nxtot + nxpad + 1)
                ymin, ymax = float(-nypad), float(nytot + nypad + 1)
            else:
                xmin = min(xmin, float(-nxpad))
                xmax = max(xmax, float(nxtot + nxpad + 1))
                ymin = min(ymin, float(-nypad))
                ymax = max(ymax, float(nytot + nypad + 1))

        xlo = cl.get_value("xlo", "left-hand X value", xmin, xmin, xmax, enforce=False)
        xhi = cl.get_value("xhi", "right-hand X value", xmax, xmin, xmax, enforce=False)
        ylo = cl.get_value("ylo", "lower Y value", ymin, ymin, ymax, enforce=False)
        yhi = cl.get_value("yhi", "upper Y value", ymax, ymin, ymax, enforce=False)

    ################################################################
    #
    # all the inputs have now been obtained. Get on with doing stuff

    # open image plot device
    imdev = hcam.pgp.Device(device)
    if width > 0 and height > 0:
        pgpap(width, height / width)

    # set up panels and axes
    nccd = len(ccds)
    ny = nccd // nx if nccd % nx == 0 else nccd // nx + 1

    # slice up viewport
    pgsubp(nx, ny)

    # plot axes, labels, titles. Happens once only
    for cnam in ccds:
        pgsci(hcam.pgp.Params["axis.ci"])
        pgsch(hcam.pgp.Params["axis.number.ch"])
        pgenv(xlo, xhi, ylo, yhi, 1, 0)
        pglab("X", "Y", "CCD {:s}".format(cnam))

    # ccd_data and object_data are long-lived
    # objects passed and stored by reference to plot updating classes
    ccd_data = {cnam: None for cnam in ccds}
    object_data = {cnam: None for cnam in ccds}

    # values of various parameters - fixed for now?
    method = 'm'
    fwhm_min = 2.0
    fwhm_fix=False
    beta = 4.0
    beta_min = 1.5
    beta_max = 10.0
    beta_fix=False
    gain = 1.1
    read = 5.5
    max_nfev = 100

    thetas = np.linspace(0, 2 * np.pi, 100)

    # Start the main loop
    total_time = 0.0
    with spooler.data_source(source, resource, first, full=False) as spool:
        for n, mccd in enumerate(spool):
            if server_or_local:
                # Handle the waiting game ...
                give_up, try_again, total_time = spooler.hang_about(
                    mccd, twait, tmax, total_time
                )

                if give_up:
                    print("ftargets stopped")
                    break
                elif try_again:
                    continue

            # We have a frame!
            nframe = mccd.head.get("NFRAME", n)

            # Trim the frames: ULTRACAM windowed data has bad columns
            # and rows on the sides of windows closest to the readout
            # which can badly affect reduction. This option strips
            # them.
            if trim:
                hcam.ccd.trim_ultracam(mccd, ncol, nrow)

            # First time setup
            if n == 0:
                # crop the calibration frames on the first frame only
                if bias is not None:
                    bias = crop_calib_frame_to(mccd, bias, "bias")
                if flat is not None:
                    flat = crop_calib_frame_to(mccd, flat, "flat")

                # compute maximum length of window name strings
                lsmax = 0
                for ccd in mccd.values():
                    for wnam in ccd:
                        lsmax = max(lsmax, len(wnam))

            pgbbuf()

            # Process each of the CCDs
            object_messages = {}
            for nc, cnam in enumerate(ccds):
                ccd = mccd[cnam]

                if not ccd.is_data():
                    # this is a junk frame from nskip > 0
                    ccd_data[cnam] = None
                    continue

                # subtract the bias
                if bias is not None:
                    ccd -= bias[cnam]

                # divide out the flat
                if flat is not None:
                    ccd /= flat[cnam]

                # Where the fancy stuff happens ...
                # estimate sky background, look for stars
                objects, messages = find_objects(
                    ccd,
                    xlo,
                    xhi,
                    ylo,
                    yhi,
                    minpix,
                    rmin,
                    pmax,
                    pmin,
                    emax,
                    nmax,
                    thresh,
                    method,
                    beta,
                    beta_min,
                    beta_max,
                    beta_fix,
                    fwhm,
                    fwhm_min,
                    fwhm_fix,
                    rejthresh,
                    max_nfev,
                    read,
                    gain,
                )

                # tack on frame number
                frames = (nframe) * np.ones(len(objects), dtype=np.int32)
                objects = append_fields([objects], ("nframe"), (frames))

                # store the data and objects for plotting
                ccd_data[cnam] = ccd
                object_data[cnam] = objects
                object_messages[cnam] = messages

            # Finally we're ready to start plotting
            for nc, cnam in enumerate(ccds):
                ccd = mccd[cnam]
                objs = object_data[cnam]

                # set to the correct panel and then plot CCD
                ix = (nc % nx) + 1
                iy = nc // nx + 1
                pgpanl(ix, iy)
                vmin, vmax = hcam.pgp.pCcd(
                    ccd,
                    iset,
                    plo,
                    phi,
                    ilo,
                    ihi,
                    xlo=xlo,
                    xhi=xhi,
                    ylo=ylo,
                    yhi=yhi,
                )

                if objs is not None and len(objs) > 0:
                    # Plot targets found

                    pgsci(core.CNAMS["red"])
                    As, Bs, Thetas, Xs, Ys = (
                        objs["a"],
                        objs["b"],
                        objs["theta"],
                        objs["x"],
                        objs["y"],
                    )
                    for a, b, theta0, x, y in zip(As, Bs, Thetas, Xs, Ys):
                        xs = x + 3 * a * np.cos(thetas + theta0)
                        ys = y + 3 * b * np.sin(thetas + theta0)
                        pgline(xs, ys)

                    pgsci(core.CNAMS["green"])
                    for xmin, xmax, ymin, ymax in zip(
                        objs["xmin"], objs["xmax"], objs["ymin"], objs["ymax"]
                    ):
                        xs = [xmin, xmax, xmax, xmin, xmin]
                        ys = [ymin, ymin, ymax, ymax, ymin]
                        pgline(xs, ys)

                    pgsci(core.CNAMS["blue"])
                    for obj in [o for o in objs if o["selected"]]:
                        x = obj["x"]
                        y = obj["y"]
                        xs = [x - rmin, x + rmin, x + rmin, x - rmin, x - rmin]
                        ys = [y - rmin, y - rmin, y + rmin, y + rmin, y - rmin]
                        pgline(xs, ys)

            # end of CCD display loop
            pgebuf()

            # save to file
            for nc, cnam in enumerate(ccds):
                ccd = mccd[cnam]
                objs = object_data[cnam]
                if objs is None or not len(objs):
                    continue

                # remove some less useful fields to save a
                # bit more space prior to saving to disk
                objs = remove_field_names(
                    objs,
                    (
                        "x2",
                        "y2",
                        "xy",
                        "cxx",
                        "cxy",
                        "cyy",
                        "hfd",
                        "cflux",
                        "cpeak",
                        "xcpeak",
                        "ycpeak",
                        "xmin",
                        "xmax",
                        "ymin",
                        "ymax",
                    ),
                )

                # open the output file for results
                if os.path.exists(output):
                    with fits.open(output) as hdul:
                        if cnam not in hdul:
                            # file exists, but first time for this CCD
                            hdul.append(fits.BinTableHDU(objs, name=cnam))
                        else:
                            # append to existing table
                            existing_table = Table(hdul[cnam].data)
                            combined_table = Table(
                                np.hstack((existing_table, objs))
                            )
                            hdul[cnam].data = combined_table.as_array()
                        hdul.writeto(output, overwrite=True)
                else:
                    # file doesn't exist, create it
                    hdul = fits.HDUList()
                    hdul.append(fits.PrimaryHDU())
                    hdul.append(fits.BinTableHDU(objs, name=cnam))
                    hdul.writeto(output, overwrite=True)

            # Now print progress indicators
            tstamp = Time(mccd.head["TIMSTAMP"], format="isot", precision=3)
            tok = "ok" if mccd.head.get("GOODTIME", True) else "nok"
            print(f"{nframe}, utc= {tstamp.iso} ({tok}), ", end="")

            # Get statistics to print out
            message = f"exp= {mccd.head['EXPTIME']:.4f}"
            for cnam in ccds:
                message += f"\n  CCD {cnam}: "

                if ccd_data[cnam] is None:
                    # skipped due to nskip > 0, no data in this frame
                    message += "none"
                    continue

                # add the image limits
                message += f"{vmin:.1f} to {vmax:.1f}, "  # TODO

                # add results of the detection and fitting
                nsel = len([o for o in object_data[cnam] if o["selected"]])
                nfail = len([o for o in object_data[cnam] if o["nfev"] == -1])
                message += f"found={len(object_data[cnam])}, selected={nsel}"
                message += f", fit={nsel-nfail}, failed={nfail}"

                # add the message for each selected target
                # TODO: this adds a lot of noise, could be optional?
                for nobj in object_messages[cnam]:
                    message += f"\n    targ {nobj}: {object_messages[cnam][nobj]}"

            # Print messages
            print(message)

            if pause > 0.0:
                # pause between frames
                time.sleep(pause)

    # At then end the plots will close automatically,
    # so block this by asking the user to confirm
    input("\nHit carriage return to close the plot(s): ")


def remove_field_names(a, names):
    """
    Removes the fields in names from the structured array a
    """
    anames = list(a.dtype.names)
    for name in names:
        if name in anames:
            anames.remove(name)
    b = a[anames]
    return b


def get_neighbour_count(xs, ys, rmin):
    """Returns number of near-neighbours of a set of points.

    Arguments:
        xs : array
            x-coordinates of points
        ys : array
            y-coordinates of points
        rmin : float
            minimum distance to consider a neighbour
    """
    points = np.c_[xs, ys]
    tree = spatial.KDTree(points)
    neighbours = tree.query_ball_tree(tree, rmin, eps=0.1)
    return [len(n) for n in neighbours]


def find_objects(
    ccd,
    xlo,
    xhi,
    ylo,
    yhi,
    minpix,
    rmin,
    pmax,
    pmin,
    emax,
    nmax,
    thresh,
    method,
    beta,
    beta_min,
    beta_max,
    beta_fix,
    fwhm,
    fwhm_min,
    fwhm_fix,
    rejthresh,
    max_nfev,
    read,
    gain,
):
    """Finds objects in a CCD, and fits FWHMs to the selected ones.

    Arguments:
        ccd : :class:`hipercam.CCD`
            CCD to search for objects in
        xlo, xhi, ylo, yhi : float
            limits of the region to search for objects in
    """
    all_objects = []
    messages = {}
    nobj = 1  # start object numbering at 1
    for wnam in ccd:
        try:
            wind = ccd[wnam].window(xlo, xhi, ylo, yhi)
        except hcam.HipercamError:
            # window may have no overlap with xlo, xhi, ylo, yhi
            continue

        # find objects and background
        wind.data = wind.data.astype("float")
        objects, bkg = findStars(wind, thresh, fwhm, return_bkg=True)

        # assign IDs to the objects across all windows
        objects = append_fields(
            [objects], ("id"), (np.arange(len(objects)) + nobj)
        )
        nobj += len(objects)

        # subtract background from frame for display purposes.
        bkg.subfrom(wind.data)
        ccd[wnam] = wind

        # remove targets with too few pixels
        objects = objects[objects["tnpix"] >= minpix]

        # run nearest neighbour search on all objects,
        # to find those with no neighbours within rmin
        neighbours = get_neighbour_count(objects["x"], objects["y"], rmin)
        objects = append_fields([objects], ("neighbours"), (neighbours))

        # select only a subset of isolated objects, with right count levels for FWHM
        # measurement, and which are not too elongated
        selected = np.array(
            [
                (
                    (obj["peak"] < pmax)
                    and (obj["peak"] > pmin * obj["thresh"])
                    and (obj["a"] < emax * obj["b"])
                    and (obj["neighbours"] == 1)
                )
                for obj in objects
            ],
            dtype=bool,
        )

        # limit selections to `nmax` brightest
        if sum(selected) > nmax:
            # sort by flux and take the brightest `nmax`
            isort = np.argsort(objects["flux"])[::-1]
            mask = np.zeros(len(objects), dtype=bool)
            mask[isort[:nmax]] = True
            selected = selected & mask
        objects = append_fields([objects], ("selected"), (selected))

        # buffer for storing the FWHMs, including NaNs for the ones that are skipped
        fwhms = np.zeros(len(objects), dtype=np.float32)
        betas = np.zeros(len(objects), dtype=np.float32)
        nfevs = np.zeros(len(objects), dtype=np.int32)

        # fit FWHMs of selected targets
        for i, obj in enumerate(objects):
            if not obj["selected"]:
                # skip this one
                fwhms[i] = np.nan
                betas[i] = np.nan
                nfevs[i] = 0
                continue

            try:
                # extract fit Window
                fwind = wind.window(
                    obj["x"] - rmin, obj["x"] + rmin, obj["y"] - rmin, obj["y"] + rmin
                )

                # uncertainties
                sigma = np.sqrt(read**2 + np.maximum(0, fwind.data) / gain)

                # fit profile
                (
                    (sky, height, x, y, fwhm, beta),
                    (esky, eheight, ex, ey, efwhm, ebeta),
                    (wfit, X, Y, chisq, nok, nrej, npar, nfev, message),
                ) = hcam.fitting.combFit(
                    wind=fwind,
                    sigma=sigma,
                    method=method,
                    sky=None,
                    height=obj["peak"],
                    x=obj["x"],
                    y=obj["y"],
                    fwhm=obj["fwhm"],
                    fwhm_min=fwhm_min,
                    fwhm_fix=fwhm_fix,
                    beta=beta,
                    beta_max=beta_max,
                    beta_fix=beta_fix,
                    thresh=rejthresh,
                    max_nfev=max_nfev,
                )
                fwhms[i] = fwhm
                betas[i] = beta
                nfevs[i] = nfev

                # keep value of beta for next round under control
                beta = min(beta_max, max(beta_min, beta))

                # store message
                messages[obj["id"]] = message

            except hcam.HipercamError as err:
                messages[obj["id"]] = f"fit failed: {err}"
                fwhms[i] = np.nan
                betas[i] = np.nan
                nfevs[i] = -1

        # save the fit results and window name
        wnams = np.array([wnam] * len(objects), dtype=str)
        objects = append_fields(
            [objects], ("ffwhm", "beta", "nfev", "wnam"), (fwhms, betas, nfevs, wnams),
        )

        all_objects.append(objects)

    return np.concatenate(all_objects), messages
