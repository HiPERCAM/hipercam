def nrtplot(args=None):
    """``nrtplot [source] (run first [twait tmax] | flist) trim ([ncol
    nrow]) (ccd (nx)) [imwidth pause tupdate plotall] bias [lowlevel
    highlevel] dark flat fmap (fpair [nhalf rmin rmax]) defect setup
    [drurl cmap imwidth imheight memory] msub iset (ilo ihi | plo phi)
    xlo xhi ylo yhi profit [method beta fwhm fwhm_min shbox smooth
    fhbox hmin read gain thresh (fwnmax fwymax fwwidth fwheight)]
    [fcosmic] (contrast crthresh nbthresh sathresh readout)``

    This is 'nrtplot' "new" rtplot, a matplotlib-based replacement for
    the current PGPLOT one. Under development.

    Plots a sequence of images as a movie in near 'real time', hence
    'rt'. Designed to be used to look at images coming in while at the
    telescope, 'nrtplot' comes with many options, a large number of
    which are hidden by default, and many of which are only prompted
    if other arguments are set correctly. If you want to see them all,
    invoke as 'nrtplot prompt'.  This is worth doing once to know
    nrtplot's capabilities.

    nrtplot can source data from both the ULTRACAM and HiPERCAM
    servers, from local 'raw' ULTRACAM and HiPERCAM files (i.e. .xml +
    .dat for ULTRACAM, 3D FITS files for HiPERCAM) and from lists of
    HiPERCAM '.hcm' files.

    nrtplot optionally allows the selection of targets to be fitted
    with gaussian or moffat profiles, and, if successful, will plot
    circles of 2x the measured FWHM in green over the selected
    targets. In this case it can also plot the history of the FWHMs as
    an aid to focussing. You can also click on targets on the fly to
    get one-off measurement which are just printed to the screen. See
    below for a note on this.

    You can re-size and zoom & pan during plotting, although it takes
    some getting used owing to the way the program blocks. For re-sizing,
    you may need to keep the left-button of the mouse down for a while
    for anything to happen. See the parameter 'memory' below which can
    help.

    When you first run it, try to get the initial fit parameters about
    right; it doesn't like to be miles out at the start for some reason
    and will refuse to fit.

    Experimental: I have added options to apply L.A.cosmic just to see what
    it returns at the moment.

    Parameters:

        source : str [hidden]
           Data source, five options for built-in sources:

             |  'hs' : HiPERCAM server
             |  'hl' : local HiPERCAM FITS file
             |  'us' : ULTRACAM server
             |  'ul' : local ULTRACAM .xml/.dat files
             |  'hf' : list of HiPERCAM hcm FITS-format files

           'hf' is used to look at sets of frames generated by 'grab'
           or converted from foreign data formats. The standard
           start-off default for ``source`` can be set using the
           environment variable HIPERCAM_DEFAULT_SOURCE. e.g. in bash
           :code:`export HIPERCAM_DEFAULT_SOURCE="us"` would ensure it
           always started with the ULTRACAM server by default. If
           unspecified, it defaults to 'hl'.

           Any instruments installed via plugins can be used as a source by
           specifying either ``<instrument>:local`` or ``<instrument>:server``.

        run : str [if source is not 'hf']
           run number to access, e.g. 'run034'

        flist : str [if source is 'hf']
           name of file list

        first : int [if source is not 'hf']
           exposure number to start from. 1 = first frame; set = 0 to always
           try to get the most recent frame (if it has changed).  For data
           from the |hiper| server, a negative number tries to get a frame not
           quite at the end.  i.e. -10 will try to get 10 from the last
           frame. This is mainly to sidestep a difficult bug with the
           acquisition system.

        twait : float [if source is not 'hf'; hidden]
           time to wait between attempts to find a new exposure, seconds.

        tmax : float [if source is not 'hf'; hidden]
           maximum time to wait between attempts to find a new exposure,
           seconds.

        trim : bool [if source starts with 'u']
           True to trim columns and/or rows off the edges of windows nearest
           the readout which can sometimes contain bad data.

        ncol : int [if trim, hidden]
           Number of columns to remove (on left of left-hand window, and right
           of right-hand windows)

        nrow : int [if trim, hidden]
           Number of rows to remove (bottom of windows)

        ccd : str
           CCD(s) to plot, '0' for all, '1 3' to plot '1' and '3' only, etc.

        nx : int [if more than 1 CCD]
           number of panels across to display for the image display.

        pause : float [hidden]
           seconds to pause between frames (defaults to 0). This is in addition
           to any time taken per frame to read and display it, so is just to slow
           things not to set an exact rate.

        tupdate : float [hidden]
           target number of seconds between plot updates. This is to
           make the plots more responsive and get round issues with
           plots freezing until the next frame comes through which can
           be especially annoying with virtual desktops. Experiments
           with ULTRACAM@NTT indicated 0.2 to 0.6 secs or so works OK.
           Main impact seems to be on drpc CPU.

        plotall : bool [hidden]
           plot all frames regardless of status (i.e. including blank frames
           when nskips are enabled (defaults to False). The profile fitting
           will still be disabled for bad frames.

        bias : str
           Name of bias frame to subtract, 'none' to ignore.

        lowlevel : float [hidden]
           Level below which a warning about low bias levels is warned. Set=0
           to ignore. Applied to first window of first CCD. 2000 about
           right for ULTRACAM.

        highlevel : float [hidden]
           Level above which a warning about high bias levels is warned. Set=0
           to ignore. Applied to first window of first CCD. 3500 about
           right for ULTRACAM.

        dark : str
           Name of dark frame to subtract, 'none' to ignore

        flat : str
           Name of flat field to divide by, 'none' to ignore. Should normally
           only be used in conjunction with a bias, although it does allow you
           to specify a flat even if you haven't specified a bias.

        fmap : str
           Name of fringe map (see e.g. `makefringe`), 'none' to ignore.

        fpair : str [if fmap is not 'none']
           Name of fringe pair file (see e.g. `setfringe`). Required if
           a fringe map has been specified.

        nhalf : int [if fmap is not 'none', hidden]
           When calculating the differences for fringe measurement,
           a region extending +/-nhalf binned pixels will be used when
           measuring the amplitudes. Basically helps the stats.

        rmin : float [if fmap is not 'none', hidden]
           Minimum individual ratio to accept prior to calculating the overall
           median in order to reduce the effect of outliers. Although all ratios
           should be positive, you might want to set this a little below zero
           to allow for some statistical fluctuation.

        rmax : float [if fmap is not 'none', hidden]
           Maximum individual ratio to accept prior to calculating the overall
           median in order to reduce the effect of outliers. Probably typically
           < 1 if fringe map was created from longer exposure data.

        defect : str
           Name of defect file, 'none' to ignore.

        setup : bool
           True/yes to access the current windows from hdriver. Useful
           during observing when setting up windows, but not normally
           otherwise. Next argument (hidden) is the URL to get to
           hdriver. Once setup, you should probably turn this off to
           avoid overloading hdriver, especially if in drift mode as
           it makes a request for the windows for every frame.

        drurl : str [if setup; hidden]
           URL needed to access window setting from the camera
           driver (ultracam, ultraspec, hipercam). The internal server
           in the camera driver must be switched on which can be done
           from the GUI.

        cmap : str [hidden]
           The matplotlib colour map to use. "Greys" gives the usual greyscale.
           "none" will give whatever the current default is. Many other choices:
           "viridis", "jet", "hot", "Oranges", etc. Enter an invalid one and
           the program will fail but return a huge list of possibles in the
           process. Note that some will not work well with the colours used
           to plot annotations.

        imwidth : float [hidden]
           image display plot width in inches (0 for default, and note
           that this will also make the height go to its default)

        imheight : float [hidden]
           image display plot height in inches (0 for default, and note
           that this will also make the width go to its default)

        memory : bool [hidden]
           stores the image display dimensions at the end as defaults for
           imwidth and imheight next time (or not). This helps when you are
           repeatedly re-starting nrtplot for the same sort of display.

        msub : bool
           subtract the median from each window before scaling for the
           image display or not. This happens after any bias subtraction.

        iset : str [single character]
           determines how the intensities are determined. There are three
           options: 'a' for automatic simply scales from the minimum to the
           maximum value found on a per CCD basis. 'd' for direct just takes
           two numbers from the user. 'p' for percentile dtermines levels
           based upon percentiles determined from the entire CCD on a per CCD
           basis.

        ilo : float [if iset='d']
           lower intensity level

        ihi : float [if iset='d']
           upper intensity level

        plo : float [if iset='p']
           lower percentile level

        phi : float [if iset='p']
           upper percentile level

        xlo : float
           left-hand X-limit for plot, initially at least since it is
           possible to re-size. For iset='p' these limits also set the
           region of the frame over which the percentil will be
           calculated. You will usually want yhi-ylo ~ xhi-xlo in
           magnitude because the aspect ratio is preserved.

        xhi : float
           right-hand X-limit for plot (can be < xlo to invert the display)

        ylo : float
           lower Y-limit for plot

        yhi : float
           upper Y-limit for plot (can be < ylo)

        profit : bool
           If profit=True, you say yes, then you will get the option
           of selecting a fixed set of objects with a cursor, and the
           program will then attempt to track these from frame to
           frame, and fit their profile. You may need to adjust
           'first' to see anything. Depending on 'fnmax', it will also
           then plot a history of the FWHM measurements, which is
           useful for focussing. The parameters used for profile fits
           are hidden and you may want to invoke the command with
           'prompt' the first time you try profile fitting. NB There
           is also an option for "on-the-fly" fits of any target: see
           the note below.

        method : str [hidden]
           this defines the profile fitting method, either a gaussian or a
           moffat profile. The latter is usually best.

        beta : float [method == 'm'; hidden]
           default Moffat exponent

        fwhm : float [hidden]
           default FWHM, unbinned pixels. Do try to get this about right as
           it affects whether the profile can be fitted at all.

        fwhm_min : float [hidden]
           minimum FWHM to allow, unbinned pixels.

        shbox : float [hidden]
           half width of box for searching for a star, unbinned
           pixels. The above-threshold target closest to the centre of
           the box in a region +/- shbox around an intial position
           will be selected. It may not be the brightest, depending
           upon your threshold settings, so use those to filter faint
           objects. If profit=True, 'shbox' should be large enough to
           allow for likely changes in position from frame to frame,
           but not too large to avoid jumping to brighter targets or
           possibly cosmic rays.

        smooth : float [hidden]
           FWHM for gaussian smoothing, binned pixels. The initial position
           for fitting is determined by finding the maximum flux in a smoothed
           version of the image in a box of width +/- shbox around the starter
           position. Typically should be comparable to the stellar width. Its
           main purpose is to combat cosmic rays which tend only to occupy a
           single pixel.

        fhbox : float [hidden]
           half width of box for profile fit, unbinned pixels. The fit box is
           centred on the position located by the initial search. It should
           normally be > ~2x the expected FWHM, and usually smaller than shbox

        hmin : float [hidden]
           height threshold to accept a fit. If the height is below this
           value, the position will not be updated. This is to help in cloudy
           conditions. The limit is applied to the image after it has been
           smoothed to make less vulnerable to seeing fluctuations. This
           can mean it can be quite small.

        read : float [hidden]
           readout noise, RMS ADU, for assigning uncertainties. Set to a -ve
           value to try to ascertain on the fly; this is advisable either if
           you don't have a bias or you apply 'msub', and it will default to
           this if not specified in this case. The value returned in this case
           includes sky noise, i.e it should be roughly sqrt(R**2+S/G) where
           R is the true read noise, S are the sky counts per pixel, and G the
           gain. If read is set -ve, two fits are carried out per target. The
           second of these should usually be pretty fast. The first is carried
           out with an assumed large read noise of 20 in order to soften the
           weights. The results reported apply to the second fit.

        gain : float [hidden]
           gain, ADU/count, for assigning uncertainties.

        thresh : float [hidden]
           sigma rejection threshold for fits

        fwnmax : int [if profit; hidden]
           maximum number of frames to buffer the FWHM plot (< 2 ==>
           no plot). It allows the FWHMs of multiple stars to be
           tracked which might be useful for focussing. The plot
           starts to "slide" once the buffers are filled.

        fwymax : float [if profit; hidden]
           maximum FWHM to plot on Y-axis [unbinned pixels]. It is
           possible to alter the value of the fly by zooming and panning
           the plot.

        fwwidth : float [if profit; hidden]
           FWHM display plot width in inches (0 for default, which will
           also cause the height to go to its default value)

        fwheight : float [if profit; hidden]
           FWHM display plot height in inches (0 for default, which will
           also cause the width to go to its default value)

        fcosmic : bool [hidden, defaults to False]
           True to identify cosmic rays using L.A.cosmic (van Dokkum 2001,
           PASP, 113, 1420) as implemented in Python package "lascosmic".
           Experimental at the moment. Just returns the number of cosmic
           rays found.

        crthresh : float
           Threshold signal-to-noise ratio of cosmic rays

        nbthresh : float
           Threshold signal-to-noise ratio of pixels neighbouring
           cosmic rays

        sathresh : float
           Threshold to flag saturated pixels

        readout : float
           readout noise, RMS ADU, for assigning uncertainties. (NB
           at the moment this is separate from "read", but they may
           be merged at some point)

    .. Note::

        To help with *dithered* long exposures especially, for which
        'profit' performs very poorly, clicking on any object will
        attempt a one-off profile fit, with results that are reported
        to the terminal. Clicks made while a frame is being processed
        are handled just before the next frame is displayed, but always
        use the frame that was on display when you clicked.

        If you don't apply bias subtraction and/or you do subtract the
        median, then the usual method to estimate the read noise fails.
        In that case, setting 'read' < 0 will force an attempt to measure
        the read noise from fluctuations in the sky. You need to ensure
        that fhbox is large enough to encompass sky regions well away from
        the target in this case.

    """

    command, args = cline.script_args(args)

    # get the inputs
    with Cline("HIPERCAM_ENV", ".hipercam", command, args) as cl:
        # register parameters
        cl.register("source", Cline.GLOBAL, Cline.HIDE)
        cl.register("run", Cline.GLOBAL, Cline.PROMPT)
        cl.register("first", Cline.LOCAL, Cline.PROMPT)
        cl.register("trim", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ncol", Cline.GLOBAL, Cline.HIDE)
        cl.register("nrow", Cline.GLOBAL, Cline.HIDE)
        cl.register("twait", Cline.LOCAL, Cline.HIDE)
        cl.register("tmax", Cline.LOCAL, Cline.HIDE)
        cl.register("flist", Cline.LOCAL, Cline.PROMPT)
        cl.register("ccd", Cline.LOCAL, Cline.PROMPT)
        cl.register("nx", Cline.LOCAL, Cline.PROMPT)
        cl.register("pause", Cline.LOCAL, Cline.HIDE)
        cl.register("tupdate", Cline.LOCAL, Cline.HIDE)
        cl.register("plotall", Cline.LOCAL, Cline.HIDE)
        cl.register("bias", Cline.GLOBAL, Cline.PROMPT)
        cl.register("lowlevel", Cline.GLOBAL, Cline.HIDE)
        cl.register("highlevel", Cline.GLOBAL, Cline.HIDE)
        cl.register("dark", Cline.GLOBAL, Cline.PROMPT)
        cl.register("flat", Cline.GLOBAL, Cline.PROMPT)
        cl.register("fmap", Cline.GLOBAL, Cline.PROMPT)
        cl.register("fpair", Cline.GLOBAL, Cline.PROMPT)
        cl.register("nhalf", Cline.GLOBAL, Cline.HIDE)
        cl.register("rmin", Cline.GLOBAL, Cline.HIDE)
        cl.register("rmax", Cline.GLOBAL, Cline.HIDE)
        cl.register("defect", Cline.GLOBAL, Cline.PROMPT)
        cl.register("setup", Cline.GLOBAL, Cline.PROMPT)
        cl.register("drurl", Cline.GLOBAL, Cline.HIDE)
        cl.register("cmap", Cline.LOCAL, Cline.HIDE)
        cl.register("imwidth", Cline.LOCAL, Cline.HIDE)
        cl.register("imheight", Cline.LOCAL, Cline.HIDE)
        cl.register("memory", Cline.LOCAL, Cline.HIDE)
        cl.register("msub", Cline.GLOBAL, Cline.PROMPT)
        cl.register("iset", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ilo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ihi", Cline.GLOBAL, Cline.PROMPT)
        cl.register("plo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("phi", Cline.LOCAL, Cline.PROMPT)
        cl.register("xlo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("xhi", Cline.GLOBAL, Cline.PROMPT)
        cl.register("ylo", Cline.GLOBAL, Cline.PROMPT)
        cl.register("yhi", Cline.GLOBAL, Cline.PROMPT)
        cl.register("profit", Cline.LOCAL, Cline.PROMPT)
        #        cl.register("nxf", Cline.LOCAL, Cline.HIDE)
        cl.register("method", Cline.LOCAL, Cline.HIDE)
        cl.register("beta", Cline.LOCAL, Cline.HIDE)
        cl.register("fwhm", Cline.LOCAL, Cline.HIDE)
        cl.register("fwhm_min", Cline.LOCAL, Cline.HIDE)
        cl.register("shbox", Cline.LOCAL, Cline.HIDE)
        cl.register("smooth", Cline.LOCAL, Cline.HIDE)
        cl.register("fhbox", Cline.LOCAL, Cline.HIDE)
        cl.register("hmin", Cline.LOCAL, Cline.HIDE)
        cl.register("read", Cline.LOCAL, Cline.HIDE)
        cl.register("gain", Cline.LOCAL, Cline.HIDE)
        cl.register("thresh", Cline.LOCAL, Cline.HIDE)
        cl.register("fwnmax", Cline.LOCAL, Cline.HIDE)
        cl.register("fwymax", Cline.LOCAL, Cline.HIDE)
        cl.register("fwwidth", Cline.LOCAL, Cline.HIDE)
        cl.register("fwheight", Cline.LOCAL, Cline.HIDE)
        cl.register("fcosmic", Cline.LOCAL, Cline.HIDE)
        cl.register("crthresh", Cline.LOCAL, Cline.PROMPT)
        cl.register("nbthresh", Cline.LOCAL, Cline.PROMPT)
        cl.register("sathresh", Cline.LOCAL, Cline.PROMPT)
        cl.register("readout", Cline.LOCAL, Cline.PROMPT)

        # get inputs
        default_source = os.environ.get("HIPERCAM_DEFAULT_SOURCE", "hl")
        source = cl.get_value(
            "source",
            "data source [hs, hl, us, ul, hf, or <instrument>:local/<instrument>:server]",
            default_source,
            lvals=available_instruments(),
        )

        # set some flags
        server_or_local = source.endswith("s") or source.endswith("l")

        if server_or_local:
            resource = cl.get_value("run", "run name", "run005")
            if source == "hs":
                first = cl.get_value("first", "first frame to plot", 1)
            else:
                first = cl.get_value("first", "first frame to plot", 1, 0)

            twait = cl.get_value(
                "twait", "time to wait for a new frame [secs]", 1.0, 0.0
            )
            tmax = cl.get_value(
                "tmax", "maximum time to wait for a new frame [secs]", 10.0, 0.0
            )

        else:
            resource = cl.get_value(
                "flist", "file list", cline.Fname("files.lis", hcam.LIST)
            )
            first = 1

        trim = cl.get_value("trim", "do you want to trim edges of windows?", True)
        if trim:
            ncol = cl.get_value("ncol", "number of columns to trim from windows", 0)
            nrow = cl.get_value("nrow", "number of rows to trim from windows", 0)
        else:
            ncol, nrow = None, None

        # define the panel grid. first get the labels and maximum dimensions
        ccdinf = spooler.get_ccd_pars(source, resource)

        nxdef = cl.get_default("nx", 3)

        if len(ccdinf) > 1:
            ccd = cl.get_value("ccd", "CCD(s) to plot [0 for all]", "0")
            if ccd == "0":
                ccds = list(ccdinf.keys())
            else:
                ccds = ccd.split()
                check = set(ccdinf.keys())
                if not set(ccds) <= check:
                    raise hcam.HipercamError("At least one invalid CCD label supplied")

            if len(ccds) > 1:
                nxdef = min(len(ccds), nxdef)
                cl.set_default("nx", nxdef)
                nx = cl.get_value("nx", "number of panels in X", 3, 1)
            else:
                nx = 1
        else:
            nx = 1
            ccds = list(ccdinf.keys())

        cl.set_default("pause", 0.0)
        pause = cl.get_value(
            "pause", "time delay to add between frame plots [secs]", 0.0, 0.0
        )

        tupdate = cl.get_value(
            "tupdate", "target time between plot updates [secs]", 0.2, 0.01
        )

        cl.set_default("plotall", False)
        plotall = cl.get_value(
            "plotall", "plot all frames, regardless of status?", False
        )

        # bias frame (if any)
        bias = cl.get_value(
            "bias",
            "bias frame ['none' to ignore]",
            cline.Fname("bias", hcam.HCAM),
            ignore="none",
        )
        if bias is not None:
            # read the bias frame
            bias = hcam.MCCD.read(bias)
            fprompt = "flat frame ['none' to ignore]"
        else:
            fprompt = "flat frame ['none' is normal choice with no bias]"

        lowlevel = cl.get_value(
            "lowlevel", "bias level lower limit for warnings", 2000.0
        )

        highlevel = cl.get_value(
            "highlevel", "bias level upper limit for warnings", 3500.0
        )

        # dark (if any)
        dark = cl.get_value(
            "dark",
            "dark frame to subtract ['none' to ignore]",
            cline.Fname("dark", hcam.HCAM),
            ignore="none",
        )
        if dark is not None:
            # read the dark frame
            dark = hcam.MCCD.read(dark)

        # flat (if any)
        flat = cl.get_value(
            "flat", fprompt, cline.Fname("flat", hcam.HCAM), ignore="none"
        )
        if flat is not None:
            # read the flat frame
            flat = hcam.MCCD.read(flat)

        # fringe file (if any)
        fmap = cl.get_value(
            "fmap",
            "fringe map ['none' to ignore]",
            cline.Fname("fmap", hcam.HCAM),
            ignore="none",
        )
        if fmap is not None:
            # read the fringe map
            fmap = hcam.MCCD.read(fmap)
            fpair = cl.get_value(
                "fpair", "fringe pair file", cline.Fname("fpair", hcam.FRNG)
            )
            fpair = fringe.MccdFringePair.read(fpair)

            nhalf = cl.get_value(
                "nhalf", "half-size of fringe measurement regions", 2, 0
            )
            rmin = cl.get_value("rmin", "minimum fringe pair ratio", -0.2)
            rmax = cl.get_value("rmax", "maximum fringe pair ratio", 1.0)

        # defect file (if any)
        defect_file = cl.get_value(
            "defect",
            "defect file ['none' to ignore]",
            cline.Fname("defect", hcam.DFCT),
            ignore="none",
        )
        if defect_file is not None:
            # read the defect frame
            defects = defect.MccdDefect.read(defect_file)
        else:
            defects = None

        # Get windows from hdriver
        setup = cl.get_value("setup", "display current hdriver window settings", False)

        if setup:
            drurl = cl.get_value(
                "drurl", "URL for driver windows", "http://192.168.1.2:5100"
            )
        else:
            drurl = None

        # Some settings for the image plots
        cmap = cl.get_value(
            "cmap", "colour map to use ['none' for mpl default]", "Greys"
        )
        cmap = None if cmap == "none" else cmap

        imwidth = cl.get_value(
            "imwidth", "image plot width [inches, 0 for default]", 0.0, 0.0
        )

        imheight = cl.get_value(
            "imheight", "image plot height [inches, 0 for default]", 0.0, 0.0
        )

        memory = cl.get_value(
            "memory", "remember finaly plot dimensions for next time?", True
        )

        # define the display intensities
        msub = cl.get_value("msub", "subtract median from each window?", True)

        iset = cl.get_value(
            "iset",
            "set intensity a(utomatically), d(irectly) or with p(ercentiles)?",
            "a",
            lvals=["a", "d", "p"],
        )
        iset = iset.lower()

        plo, phi = 5, 95
        ilo, ihi = 0, 1000
        if iset == "d":
            ilo = cl.get_value("ilo", "lower intensity limit", 0.0)
            ihi = cl.get_value("ihi", "upper intensity limit", 1000.0)
        elif iset == "p":
            plo = cl.get_value(
                "plo", "lower intensity limit percentile", 5.0, 0.0, 100.0
            )
            phi = cl.get_value(
                "phi", "upper intensity limit percentile", 95.0, 0.0, 100.0
            )

        # region to plot
        for i, cnam in enumerate(ccds):
            nxtot, nytot, nxpad, nypad = ccdinf[cnam]
            if i == 0:
                xmin, xmax = float(-nxpad), float(nxtot + nxpad + 1)
                ymin, ymax = float(-nypad), float(nytot + nypad + 1)
            else:
                xmin = min(xmin, float(-nxpad))
                xmax = max(xmax, float(nxtot + nxpad + 1))
                ymin = min(ymin, float(-nypad))
                ymax = max(ymax, float(nytot + nypad + 1))

        xlo = cl.get_value("xlo", "left-hand X value", xmin, xmin, xmax, enforce=False)
        xhi = cl.get_value("xhi", "right-hand X value", xmax, xmin, xmax, enforce=False)
        ylo = cl.get_value("ylo", "lower Y value", ymin, ymin, ymax, enforce=False)
        yhi = cl.get_value("yhi", "upper Y value", ymax, ymin, ymax, enforce=False)

        # many parameters for profile fits, although most are not
        # plotted by default
        profit = cl.get_value("profit", "do you want accumulating profile fits?", False)

        #            nxf = cl.get_value("nxf", "maximum number of fit panels in X", 3)
        method = cl.get_value(
            "method", "fit method g(aussian) or m(offat)", "m", lvals=["g", "m"]
        )
        if method == "m":
            beta = cl.get_value(
                "beta", "initial exponent for Moffat fits", 5.0, 0.5, 20.0
            )
        else:
            beta = 0.0
        fwhm_min = cl.get_value(
            "fwhm_min", "minimum FWHM to allow [unbinned pixels]", 1.5, 0.01
        )
        fwhm = cl.get_value(
            "fwhm",
            "initial FWHM [unbinned pixels] for profile fits",
            6.0,
            fwhm_min,
        )
        shbox = cl.get_value(
            "shbox",
            "half width of box for initial location of target [unbinned pixels]",
            11.0,
            2.0,
        )
        smooth = cl.get_value(
            "smooth",
            "FWHM for smoothing for initial object detection [binned pixels]",
            6.0,
        )
        fhbox = cl.get_value(
            "fhbox",
            "half width of box for profile fit [unbinned pixels]",
            21.0,
            3.0,
        )
        hmin = cl.get_value("hmin", "minimum peak height to accept the fit", 50.0)
        if bias is None or msub:
            cl.set_default("read", -1.0)
        read = cl.get_value("read", "readout noise, RMS ADU", -1.0)
        gain = cl.get_value("gain", "gain, ADU/e-", 1.0)
        thresh = cl.get_value("thresh", "number of RMS to reject at", 4.0)

        fwnmax = cl.get_value(
            "fwnmax", "maximum number of frame to buffer FWHM [0 to ignore]", 100, 0
        )

        fwymax = cl.get_value(
            "fwymax",
            "maximum FWHM value to plot on Y-axis [unbinned pixels]",
            10.0,
            2.0,
        )

        fwwidth = cl.get_value(
            "fwwidth", "FWHM plot width [inches, 0 for default]", 0.0, 0.0
        )

        fwheight = cl.get_value(
            "fwheight", "FWHM plot height [inches, 0 for default]", 0.0, 0.0
        )

        cl.set_default("fcosmic", False)
        fcosmic = cl.get_value("fcosmic", "find cosmic rays", False)
        # disable if lacosmic is not available
        if lacosmic is None and fcosmic:
            warnings.warn("lacosmic not available, disabling cosmic ray removal")
            fcosmic = False

        if fcosmic:
            crthresh = cl.get_value(
                "crthresh", "threshold S-to-N for cosmic ray detection", 5.0, 0.0
            )
            nbthresh = cl.get_value(
                "nbthresh", "threshold S-to-N for neighbour pixels", 3.0, 0.0
            )
            sathresh = cl.get_value("sathresh", "saturation threshold", 65535.0)
            readout = cl.get_value("readout", "readout noise, RMS ADU", 2.5, 0.0)

    ##########################################################################

    # Phew. We finally have all the inputs and now can now display stuff.

    # Initialise the plot managers to None, so we can create them on the first frame
    imanager = None
    fwhmmanager = None

    # Keep track of any profit targets and setup windows
    pfit_targets = None
    pfit_results = None
    pfit_fwhms = None
    swindows = None

    # Start the main loop
    total_time = 0.0
    with spooler.data_source(source, resource, first, full=False) as spool:
        for n, mccd in enumerate(spool):
            if server_or_local:
                # Handle the waiting game ...
                # Includes some awkward stuff involving updating on a cycle
                # faster than twait to make the plots more responsive,
                # if twait is long.
                updaters = []
                if imanager is not None:
                    updaters.append(imanager.refresh)
                if fwhmmanager is not None:
                    updaters.append(fwhmmanager.refresh)

                give_up, try_again, total_time = spooler.hang_about(
                    mccd, twait, tmax, total_time, updaters, tupdate
                )

                if give_up:
                    print("nrtplot stopped")
                    break
                elif try_again:
                    continue

            # We have a frame!
            nframe = mccd.head.get("NFRAME", n + 1)

            # Accumulate errors from here on to print later
            emessages = []

            # Trim the frames: ULTRACAM windowed data has bad columns
            # and rows on the sides of windows closest to the readout
            # which can badly affect reduction. This option strips
            # them.
            if trim:
                hcam.ccd.trim_ultracam(mccd, ncol, nrow)

            # Bias level checks
            if lowlevel != 0.0:
                median = mccd.get_num(0).get_num(0).median()
                if median < lowlevel:
                    emessages.append(
                        "  ** low bias level, median vs limit: "
                        f"{median:.1f} vs {lowlevel:.1f}"
                    )
            if highlevel != 0.0:
                try:
                    median = mccd.get_num(0).get_num(1).median()
                except:
                    median = mccd.get_num(0).get_num(0).median()
                if median > highlevel:
                    emessages.append(
                        "  ** high bias level, median vs limit: "
                        f"{median:.1f} vs {highlevel:.1f}"
                    )

            # First time setup
            if n == 0:
                # crop the calibration frames on the first frame only
                if bias is not None:
                    bias = crop_calib_frame_to(mccd, bias, "bias")
                if dark is not None:
                    dark = crop_calib_frame_to(mccd, dark, "dark")
                if flat is not None:
                    flat = crop_calib_frame_to(mccd, flat, "flat")
                if fmap is not None:
                    fmap = crop_calib_frame_to(mccd, fmap, "fmap")
                    fpair = fpair.crop(mccd, nhalf)

            if setup:
                # Get setup windows from hdriver / udriver.
                # Fair bit of error checking needed.
                # 'swindows' is a list of (llx,lly,nx,ny) tuples if something is found.
                try:
                    r = requests.get(drurl, timeout=0.2)
                    if r.text.strip() == "No valid data available":
                        emessages.append(
                            f"  ** bad return from hdriver = {r.text.strip()}"
                        )
                        swindows = None
                    elif r.text.strip() == "fullframe":
                        # to help Stu out a bit, effectively just
                        # ignore this one
                        swindows = None
                    else:
                        # OK, got something
                        lines = r.text.split("\r\n")
                        xbinh, ybinh, nwinh = lines[0].split()
                        xbinh, ybinh, nwinh = int(xbinh), int(ybinh), int(nwinh)
                        swindows = []
                        for line in lines[1 : nwinh + 1]:
                            llxh, llyh, nxh, nyh = line.split()
                            swindows.append((int(llxh), int(llyh), int(nxh), int(nyh)))
                        # check the number of windows is correct
                        if nwinh != len(swindows):
                            emessages.append(
                                f"  ** expected {nwinh} windows from"
                                f" (u/h)driver but got {len(swindows)}"
                            )
                            swindows = None
                except (
                    requests.exceptions.ConnectionError,
                    socket.timeout,
                    requests.exceptions.Timeout,
                ) as err:
                    emessages.append(f"  ** hdriver error: {err!r}")
                    swindows = None

            # Process each of the CCDs
            ncosmic = {cnam: 0 for cnam in ccds}
            for cnam in ccds:
                ccd = mccd[cnam]

                if not ccd.is_data() and not plotall:
                    # this is a junk frame from nskip > 0
                    # skip it, unless plotall is True
                    continue

                # lots of frame processing and calibration to do
                if fcosmic:
                    # save a copy for later in order to mask saturated stars
                    raw = ccd.copy()

                # subtract the bias
                if bias is not None:
                    ccd -= bias[cnam]

                # subtract the dark, scaling by exposure time
                if dark is not None:
                    cexpose = ccd.head["EXPTIME"]
                    dexpose = dark.head["EXPTIME"]
                    if bias is not None:
                        bexpose = bias.head.get("EXPTIME", 0.0)
                    else:
                        bexpose = 0.0
                    scale = (cexpose - bexpose) / dexpose
                    ccd -= scale * dark[cnam]

                # divide out the flat
                if flat is not None:
                    ccd /= flat[cnam]

                # remove fringes
                if fmap is not None and cnam in fmap and cnam in fpair:
                    fscale = fpair[cnam].scale(ccd, fmap[cnam], nhalf, rmin, rmax)
                    ccd -= fscale * fmap[cnam]

                # cosmic ray detection
                if fcosmic:
                    for wind, rwind in zip(ccd.values(), raw.values()):
                        smask = rwind.data >= sathresh
                        _, crmask = lacosmic.lacosmic(
                            wind.data,
                            crthresh,
                            nbthresh,
                            mask=smask,
                            effective_gain=gain,
                            readnoise=readout * gain,
                        )
                        ncosmic[cnam] += len(crmask[crmask])

                # subtract median from each window
                if msub:
                    for wind in ccd.values():
                        wind -= wind.median()

            # Select targets for profile fitting
            if profit and pfit_targets is None:
                if not all(mccd[cnam].is_data() for cnam in ccds):
                    # Due to nskips, we need to wait until all CCDs have data
                    continue

                # We have at least one proper exposure of all CCDs
                # from which stars can be selected.

                # create the plot
                fig, axs = hcam.mpl.plot_frame(
                    mccd=mccd,
                    cnams=ccds,
                    ncols=nx,
                    defects=defects,
                    cmap=cmap,
                    iset=iset,
                    ilim=(plo, phi) if iset == "p" else (ilo, ihi),
                    region=(xlo, xhi, ylo, yhi),
                    title="Profile fit selection",
                    figsize=(imwidth, imheight),
                )

                # print out instructions for the user
                print(
                    "Use the SpaceBar to select targets for profile fitting; "
                    "q(uit) to exit selection and start animation"
                )

                # create the picker class and connect it to the figure
                picker = PickProfitTargets(
                    mccd,
                    fig,
                    axs,
                    shbox,
                    fwhm,
                    beta,
                    method,
                    smooth,
                    fhbox,
                    hmin,
                    fwhm_min,
                    read,
                    gain,
                    thresh,
                )
                fig.canvas.mpl_connect("key_press_event", picker._keyPressEvent)

                # finally set up the plot for interactive mode and display
                hcam.mpl.setup_plot(fig)
                plt.show()

                # once we return, targets should be selected, if any
                if len(picker.targets) > 0:
                    # create a dict of targets, with each assigned a number
                    pfit_targets = {
                        i + 1: pfit for i, pfit in enumerate(picker.targets)
                    }

                    # create deques to hold frame numbers and FWHMs for each target
                    pfit_fwhms = {
                        ntarg: (deque(maxlen=fwnmax), deque(maxlen=fwnmax))
                        for ntarg in pfit_targets
                    }
                else:
                    # no targets selected, so disable profile fitting
                    profit = False

            # Fit profile for each target, if we have any
            if pfit_targets is not None:
                plot_pfits = {ntarg: None for ntarg in pfit_targets}
                # First update search box positions. In normal
                # operation this moves the boxes to match the target
                # positions previously fitted.
                for ntarg, pfit in pfit_targets.items():
                    pfit.update_sbox()

                # Carry out fits
                pfit_results = {ntarg: None for ntarg in pfit_targets}
                for ntarg, pfit in pfit_targets.items():
                    cnam = pfit.cnam
                    if mccd[cnam].is_data():
                        # Do the fit and store the results and message
                        # If the fit fails, results will be None
                        pfit_results[ntarg] = pfit.fit(
                            ccd=mccd[cnam],
                            method=method,
                            smooth=smooth,
                            fhbox=fhbox,
                            hmin=hmin,
                            fwhm_min=fwhm_min,
                            read=read,
                            gain=gain,
                            thresh=thresh,
                        )

                # Store latest results for plotting
                # We only want to plot the target if the fit was successful,
                # so 'plot_pfits' is just a filtered version of 'pfit_targets'.
                for ntarg, pfit in pfit_targets.items():
                    if pfit_results[ntarg] is not None:
                        plot_pfits[ntarg] = pfit
                        pfit_fwhms[ntarg][0].append(nframe)
                        pfit_fwhms[ntarg][1].append(pfit.fwhm)
            else:
                plot_pfits = {}

            # Finally we're ready to start plotting
            # First the main image plot
            if imanager is None:
                # First time through, create the image plot manager
                imanager = ImageManager(
                    mccd=mccd,
                    pfits=plot_pfits,
                    defects=defects,
                    swindows=swindows,
                    cnams=ccds,
                    plotall=plotall,
                    ncols=nx,
                    iset=iset,
                    ilim=(plo, phi) if iset == "p" else (ilo, ihi),
                    region=(xlo, xhi, ylo, yhi),
                    cmap=cmap,
                    figsize=(imwidth, imheight),
                    shbox=shbox,
                    fwhm=fwhm,
                    beta=beta,
                    method=method,
                    smooth=smooth,
                    fhbox=fhbox,
                    hmin=hmin,
                    fwhm_min=fwhm_min,
                    read=read,
                    gain=gain,
                    thresh=thresh,
                )

                if memory:
                    # define object to handle adjusting the figure size
                    cleanup = CleanUp(
                        "HIPERCAM_ENV", ".hipercam", command, args, imanager.fig
                    )
                    signal(SIGINT, cleanup)

                # start live display
                plt.show(block=False)
                plt.pause(0.1)

            # Update the image plot (done on every loop)
            imanager.update(mccd, plot_pfits, swindows)

            if pfit_fwhms and fwnmax > 1:
                # Plot change in FWHM over time
                if fwhmmanager is None:
                    # First time through, create the FWHM plot manager
                    fwhmmanager = FwhmManager(
                        pfit_fwhms,
                        xlo=nframe - 1,
                        xhi=nframe + fwnmax + 1,
                        fwmax=fwymax,
                        figsize=(fwwidth, fwheight),
                    )
                    plt.show(block=False)
                    plt.pause(0.1)

                # Update the FWHM plot (done on every loop)
                fwhmmanager.update(pfit_fwhms)

            # Now print progress indicators
            tstamp = Time(mccd.head["TIMSTAMP"], format="isot", precision=3)
            tok = "ok" if mccd.head.get("GOODTIME", True) else "nok"
            print(f"{nframe}, utc= {tstamp.iso} ({tok}), ", end="")

            # Get statistics to print out
            message = f"exp= {mccd.head['EXPTIME']:.4f}"
            for cnam in ccds:
                message += f", CCD {cnam}: "

                if not mccd[cnam].is_data():
                    # skipped due to nskip > 0, no data in this frame
                    message += "none"
                    continue

                # add the image limits
                vmin, vmax = imanager.get_ilim(cnam)
                message += f"{vmin:.1f} to {vmax:.1f}"

                # add cosmic ray counts
                if fcosmic:
                    message += f", nc: {ncosmic[cnam]}"

            # Print messages
            print(message)
            for emessage in emessages:
                print(emessage)

            if pfit_targets is not None:
                # Print out the results of the profile fits, if any
                for ntarg in pfit_results:
                    if pfit_results[ntarg] is not None:
                        message = pfit_results[ntarg][1]
                        print(f"  Target {ntarg}, {message}")

                # If we have two (and only two) fitted targets,
                # then find the angle between them
                if (
                    len(pfit_targets) == 2
                    and pfit_results[1] is not None
                    and pfit_results[2] is not None
                ):
                    dx = pfit_targets[2].x - pfit_targets[1].x
                    dy = pfit_targets[2].y - pfit_targets[1].y
                    theta = Angle(np.arctan2(dy, dx), unit=u.rad).to(u.deg)
                    theta = theta.wrap_at(360 * u.deg).to_value()
                    print(
                        f"  From target 1 to 2: Θ = {theta:.2f}° "
                        "(anti-clockwise from horizontal)"
                    )

            if pause > 0.0:
                # pause between frames
                if pause > 2 * tupdate:
                    # run the updaters if pause is a little long.
                    # designed to make the plot more responsive
                    nupdate = int(pause / tupdate)
                    for _ in range(nupdate):
                        time.sleep(pause / nupdate)
                        if imanager is not None:
                            imanager.refresh()
                        if fwhmmanager is not None:
                            fwhmmanager.refresh()
                else:
                    # just pause because the updates will come
                    time.sleep(pause)

    # At the end the plots will close automatically,
    # so block this by asking the user to confirm
    input("\nHit carriage return to close the plot(s): ")

    if memory:
        cleanup.finish()


class CleanUp:
    """
    Handle adjusting plot width defaults in a way that can be used
    as a handler for signal
    """

    def __init__(self, hipenv, hipconf, command, args, fig):
        self.hipenv = hipenv
        self.hipconf = hipconf
        self.command = command
        self.args = args
        self.fig = fig

    def __call__(self, signal_recieved, frame):
        self.finish()
        sys.exit(1)

    def finish(self):
        with Cline(self.hipenv, self.hipconf, self.command, self.args) as cl:
            width = self.fig.get_figwidth()
            height = self.fig.get_figheight()
            cl.register("imwidth", Cline.LOCAL, Cline.HIDE)
            cl.register("imheight", Cline.LOCAL, Cline.HIDE)
            cl.set_default("imwidth", width)
            cl.set_default("imheight", height)
            print(
                f"\nImage display size updated to width, height = {width}, {height} [memory=True]"
            )


class ImageManager(hcam.mpl.AnimationManager):
    """Class to control the image animation.

    Initialising it creates the figure and the animated artists for the first frame.
    After that, call ``update`` once per frame to update the artists,
    and ``refresh`` as often as needed to keep the window responsive.

    Allows plotting of defects and setup windows, and the search box and
    fitted positions of any profile fit targets.

    """

    def __init__(
        self,
        mccd,
        pfits,
        defects,
        swindows,
        cnams,
        plotall,
        ncols,
        iset,
        ilim,
        region,
        cmap,
        figsize,
        shbox,
        fwhm,
        beta,
        method,
        smooth,
        fhbox,
        hmin,
        fwhm_min,
        read,
        gain,
        thresh,
    ):
        """Initialises and manages the plot.

        Arguments:

        mccd : :class:`MCCD`
            The first frame to display.
            Used to create the artists on initialisation;
            new data should be passed to `update`.

        pfits : dict of {int: :class:`Pfit` or None}
            One entry per target being profile fitted, keys are target numbers.
            Contains the Pfit class, or None if no fit was made for that target.
            Used to create the artists on initialisation;
            new data should be passed to `update`.

        defects : :class:`MccdDefect` | None
            Group of defects to plot on each frame, if any.

        swindows : list of tuples, or None
            List of setup windows to plot on the frame,
            each tuple is (llxh, llyh, nxh, nyh)

        cnams : list of str
            The names of the CCDs to plot.

        plotall : bool
            If True, plot all frames, even if they contain no data.

        ncols : int
            The number of columns in the grid of subplots

        iset : str
            How to set the intensity scale for the images:
                'a' for automatic min/max range
                'p' for percentiles (set using `ilim`)
                'd' for direct values (set using `ilim`)

        ilim : tuple[float, float] | None
            Lower and upper limits for the intensity scaling.

        region : tuple[int, int, int, int] | None
            The region to plot, values are (xmin, xmax, ymin, ymax)
            If None, the entire CCD is displayed.
            If iset='p', only this region is used to compute the percentiles for
            intensity scaling.

        cmap : str  | None
            Matplotlib colour map. None gives default

        figsize : tuple[float, float] | None
            The width and height of the figure, in inches.
            If None, the default size is used.

        shbox, fwhm, beta, method, smooth, fhbox, hmin, fwhm_min, read,
        gain, thresh are profile fitting parameters described elsewhere.
        They are sent to a cursor selection routine.

        """
        # create empty figure and axes
        self.fig, self.axs = hcam.mpl.create_figure(
            cnams=cnams,
            ncols=ncols,
            region=region,
            title="CCD display",
            figsize=figsize,
        )

        # initialise the animation manager with the figure
        super().__init__(self.fig)

        # setup the figure for interactive mode
        hcam.mpl.setup_plot(self.fig, disable_shortcuts=False)

        # inputs for the image plots
        self.defects = defects
        self.swindows = None  # will be set in update_images
        self.cnams = cnams
        self.plotall = plotall
        self.iset = iset
        self.ilim = ilim
        self.region = region
        self.cmap = cmap

        # print out instructions for the user
        print("\n(use the SpaceBar to select targets for one-off profile fits)\n")

        # create the picker class and connect it to the figure
        self.picker = PickProfit(
            mccd,
            self.fig,
            self.axs,
            shbox,
            fwhm,
            beta,
            method,
            smooth,
            fhbox,
            hmin,
            fwhm_min,
            read,
            gain,
            thresh,
        )
        self.fig.canvas.mpl_connect("key_press_event", self.picker._keyPressEvent)

        # create and update the artists
        self.img_artists = {cnam: None for cnam in self.cnams}
        self.targ_artists = {ntarg: None for ntarg in pfits}
        self.update(mccd, pfits, swindows)

        # adjust the layout to prevent overlap
        # (can only do after the artists are created)
        self.fig.tight_layout()

    def draw_artists(self):
        """Draw all of the animated artists."""
        for cnam in self.axs:
            # Draw the CCD artists
            if self.img_artists[cnam] is not None:
                # 'ccd' has values which are all lists of artists
                for artists in self.img_artists[cnam]["ccd"].values():
                    for artist in artists:
                        self.fig.draw_artist(artist)

                # so does 'defects'
                for artists in self.img_artists[cnam]["defects"].values():
                    for artist in artists:
                        self.fig.draw_artist(artist)

                # but 'swindows' is a plain list of artists
                for artist in self.img_artists[cnam]["swindows"]:
                    self.fig.draw_artist(artist)

        # Draw the target artists
        for artists in self.targ_artists.values():
            # targ_artists also contains lists (dot, circ, box)
            if artists is not None:
                for artist in artists:
                    self.fig.draw_artist(artist)

    def update(self, mccd, pfits=None, swindows=None):
        """Create or update the artists with new data."""
        # Update the artists for the CCDs and setup windows
        self._update_images(mccd, swindows)

        # Update the artists for the targets, if any
        if pfits is not None:
            self._update_targets(pfits)

        # Refresh the display
        self.refresh(redraw=True)

    def _update_images(self, mccd, swindows=None):
        """Create or update the CCD artists."""
        # update the picker with the new data
        self.fig.canvas.flush_events()
        self.picker.update(mccd)

        # NB img_artists is a dictionary that will be created to contain all of the
        # artists plotted on each CCD panel.
        # The dictionary keys are the CCD names, and each value is another dictionary
        # with keys:
        #     'ccd' : dictionary as returned by pCcd
        #     'defects' : dictionary as returned by pCcdDefect. Can be just {}
        #     'swindows' : list of Artists, can be just []
        new_artists = {}

        # update CCD (and defect) artists
        for cnam in self.img_artists:
            if not mccd[cnam].is_data() and not self.plotall:
                # no new frame, just pass old artists through (unless plotall is True)
                new_artists[cnam] = self.img_artists[cnam]
            else:
                # create/update the animated artists
                old_artists = self.img_artists[cnam]
                new_artists[cnam] = {}

                # get scale limits
                vmin, vmax = hcam.mpl.get_scale_limits(
                    mccd[cnam],
                    mode=self.iset,
                    limits=self.ilim,
                    region=self.region,
                )

                # plot the CCD
                new_artists[cnam]["ccd"] = hcam.mpl.pCcd(
                    ax=self.axs[cnam],
                    ccd=mccd[cnam],
                    vmin=vmin,
                    vmax=vmax,
                    cmap=self.cmap,
                    tlabel=f"CCD {cnam}",
                    animated=True,
                    artists=old_artists["ccd"] if old_artists is not None else None,
                )

                # plot the defects, if any
                if self.defects is not None and cnam in self.defects:
                    new_artists[cnam]["defects"] = hcam.mpl.pCcdDefect(
                        self.axs[cnam],
                        self.defects[cnam],
                        animated=True,
                        artists=(
                            old_artists["defects"] if old_artists is not None else None
                        ),
                    )
                else:
                    new_artists[cnam]["defects"] = {}

                # In this case we are setting up for the first time
                # need to re-draw to avoid irritating distorted image
                if old_artists is None:
                    self.fig.canvas.draw()

        # update swindow artists
        for cnam in self.img_artists:
            # The setup windows can change in number as well as size.
            # We only need to update the artists if the windows have changed.
            # Note we still do this even if ccd.is_data() is False,
            # because we want to update the windows even on a frame that is skipped,
            # which is why this is a separate loop.
            ax = self.axs[cnam]
            old_artists = self.img_artists[cnam]
            if swindows is None or self.swindows != swindows:
                # the windows have changed (or been removed)
                # delete any existing artists
                if old_artists is not None and old_artists["swindows"] is not None:
                    for artist in old_artists["swindows"]:
                        artist.remove()

            sartists = []
            if swindows is None:
                # no windows to plot, so just keep an empty list
                pass
            elif old_artists is None or self.swindows != swindows:
                # first time, or the windows have changed, so create new artists
                for llxh, llyh, nxh, nyh in swindows:
                    (box,) = ax.plot(
                        [
                            llxh - 0.5,
                            llxh + nxh - 0.5,
                            llxh + nxh - 0.5,
                            llxh - 0.5,
                            llxh - 0.5,
                        ],
                        [
                            llyh - 0.5,
                            llyh - 0.5,
                            llyh + nyh - 0.5,
                            llyh + nyh - 0.5,
                            llyh - 0.5,
                        ],
                        "--",
                        color=hcam.mpl.Params["setup.box.col"],
                        animated=True,
                    )
                    sartists.append(box)
            else:
                # the windows are the same, so reuse the existing artists (if any)
                sartists = old_artists["swindows"]

            if new_artists[cnam] is not None:
                new_artists[cnam]["swindows"] = sartists

        # save the current windows for comparison next time
        self.swindows = swindows

        # Finally, update the artists
        self.img_artists = new_artists

    def _update_targets(self, pfits):
        """Create or update the target artists."""
        new_artists = {}
        for ntarg, pfit in pfits.items():
            old_artists = self.targ_artists[ntarg]
            if pfit is None:
                # the fit failed on this frame, so just pass through the old artists
                # TODO: Is this right? Maybe we should mark it red, like in ftargets
                new_artists[ntarg] = old_artists
            else:
                ax = self.axs[pfit.cnam]
                if old_artists is None:
                    # First time, create the new artists
                    # Each target has three artists:
                    #     - a dot for the target position
                    #     - a circle of radius equal to the FWHM
                    #     - a search box
                    new_artists[ntarg] = pfit.plot(ax, True)
                else:
                    # In this case we have already created the artists,
                    # so we just update them with the new data
                    if old_artists is None:
                        # The artists have yet to be made
                        new_artists[ntarg] = pfit.plot(ax, True)
                    else:
                        # they exist already and need updating
                        dot, circ, sbox = old_artists
                        # set_data must take a sequence from MPL 3.9
                        dot.set_data((pfit.x,), (pfit.y,))
                        circ.set_center((pfit.x, pfit.y))
                        circ.set_radius(pfit.fwhm)
                        xlo, xhi, ylo, yhi = pfit.region()
                        sbox.set_data(
                            [xlo, xhi, xhi, xlo, xlo], [ylo, ylo, yhi, yhi, ylo]
                        )
                        new_artists[ntarg] = (dot, circ, sbox)

         # Finally, update the artists
        self.targ_artists = new_artists

    def get_ilim(self, cnam):
        """Returns the current intensity limits for the specified CCD."""
        if self.img_artists[cnam] is None:
            return None
        imgs = self.axs[cnam].get_images()
        return imgs[0].get_clim()  # for the first window, but should be the same


class FwhmManager(hcam.mpl.AnimationManager):
    """Class to start and control the FWHM history animation."""

    def __init__(self, fwhm_data, xlo, xhi, fwmax, figsize=None):
        """
        Initialises the FWHM history plot.

        Arguments:

        fwhm_data : dict[int, tuple[deque[float], deque[float]]]
            dict of FWHM data for each target
            keys are target numbers, values are tuples of (frame numbers, FWHMs)
            when the deques are full, the oldest data is dropped from the left

        xlo : float
            left-hand X -limit (inital) for plot

        xhi : float
            right-hand X -limit (inital) for plot

        fwmax : float
            maximum height for FWHM plot in pixels

        figsize : tuple[float, float] | None
            The width and height of the figure, in inches.
            If None, the default size is used.

        """
        # create empty figure and axes
        self.fig = plt.figure()
        self.fig.canvas.manager.set_window_title("FWHM vs frame number")
        if figsize is not None and figsize[0] > 0 and figsize[1] > 0:
            self.fig.set_size_inches(figsize)
        self.ax = self.fig.add_subplot(animated=True)

        # initialise the animation manager with the figure
        super().__init__(self.fig)

        # set axis limits
        self.fwmax = fwmax
        self.xlo = xlo
        self.xhi = xhi
        self.ylo = 0
        self.yhi = fwmax
        self.ax.set_xlim(self.xlo, self.xhi)
        self.ax.set_ylim(self.ylo, self.yhi)

        # plot a line for each target
        self.fwhm_artists = {ntarg: None for ntarg in fwhm_data}
        self.update(fwhm_data)

        # plot formatting
        self.ax.set_xlabel("Frame number")
        self.ax.set_ylabel("FWHM [unbinned pixels]")
        self.ax.legend()

    def draw_artists(self):
        """Draw all of the animated artists."""
        # Draw the axes
        self.fig.draw_artist(self.ax)

        # Draw the artists
        for artist in self.fwhm_artists.values():
            if artist is not None:
                self.fig.draw_artist(artist)

    def update(self, fwhm_data):
        """Create or update the artists with new data."""
        xmax = None
        for ntarg, (xs, ys) in fwhm_data.items():
            if self.fwhm_artists[ntarg] is None:
                # First time, create the new artists
                (artist,) = self.ax.plot(xs, ys, animated=True, label=f"{ntarg}")
                self.fwhm_artists[ntarg] = artist
            else:
                # Update existing artists
                self.fwhm_artists[ntarg].set_data(xs, ys)
            # Keep track of the maximum x value,
            # so we can adjust the x-axis limits if needed
            if len(xs):
                xmax = max(xs) if xmax is None else max(xmax, max(xs))

        if xmax is not None and xmax > self.xhi - 1:
            # update axes limits
            xadd = xmax - self.xhi + 1
            self.xlo += xadd
            self.xhi += xadd
            self.ax.set_xlim(self.xlo, self.xhi)
            # crop out points outside of the buffer
            # note the deques should drop data automatically,
            # but if some frames are skipped or have failed fits then there might still
            # be older items
            for ntarg, (xs, ys) in fwhm_data.items():
                while len(xs) and xs[0] <= self.xlo:
                    xs.popleft()
                    ys.popleft()

        # Finally, refresh the display
        self.refresh(redraw=True)


class PickProfitTargets:
    """Class to pick targets for ongoing profile fitting."""

    def __init__(
        self,
        mccd,
        fig,
        axs,
        shbox,
        fwhm,
        beta,
        method,
        smooth,
        fhbox,
        hmin,
        fwhm_min,
        read,
        gain,
        thresh,
    ):
        # image content data
        self.mccd = mccd

        # figure and axes
        self.fig = fig
        self.axs = axs
        self.axnams = {ax: cnam for cnam, ax in axs.items()}  # reverse for events

        # fitting params
        self.shbox = shbox
        self.fwhm = fwhm
        self.beta = beta
        self.method = method
        self.smooth = smooth
        self.fhbox = fhbox
        self.hmin = hmin
        self.fwhm_min = fwhm_min
        self.read = read
        self.gain = gain
        self.thresh = thresh

        # accumulating target list
        self.targets = []

    def _keyPressEvent(self, event):
        """
        Where stuff is done
        """
        if event.key == "q":
            plt.close()
            print(f"Selected {len(self.targets)} target(s) for profile fitting")
            return

        if event.key == " " and event.inaxes is not None:
            # clicked inside an Axes
            ax = event.inaxes

            # extract the CCD
            cnam = self.axnams[ax]
            ccd = self.mccd[cnam]

            # check that the position is inside a window
            x, y = event.xdata, event.ydata
            wnam = ccd.inside(x, y, 2)

            if wnam is not None:
                # store the position, Window label, target
                # number, box size fwhm, beta
                pfit = Pfit(cnam, wnam, x, y, self.shbox, self.fwhm, self.beta)
                results, message = pfit.fit(
                    ccd,
                    self.method,
                    self.smooth,
                    self.fhbox,
                    self.hmin,
                    self.fwhm_min,
                    self.read,
                    self.gain,
                    self.thresh,
                )
                if results is not None:
                    # fitted OK
                    self.targets.append(pfit)
                    print(
                        f"  Target {len(self.targets)} added "
                        f"at initial x,y = {x:.2f}, {y:.2f} "
                        f"in CCD {cnam}, window {wnam}, "
                        "refined by fit with results:"
                    )
                    print(f"    {message}")
                    pfit.plot(ax)
                    self.fig.canvas.draw()
                else:
                    print(
                        f"  ** fit failed for position x,y = {x:.2f}, {y:.2f} "
                        f"in CCD {cnam}, window {wnam}; no new target added"
                    )
                    print(f"  ** fit message = {message}")


